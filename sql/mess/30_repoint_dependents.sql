CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_CATALOG.VW_CANNIBALIZATION_CANDIDATES (
	GAME_A_NAME,
	GAME_B_NAME,
	PUBLISHER_NAME,
	WEIGHTED_OVERLAP,
	GENRE_OVERLAP,
	PLATFORM_OVERLAP,
	MECHANIC_OVERLAP,
	GAMEPLAY_OVERLAP,
	OVERLAP_TIER
) AS
SELECT
    s.GAME_A_NAME, s.GAME_B_NAME,
    ga.PUBLISHER_NAME,
    s.WEIGHTED_OVERLAP, s.GENRE_OVERLAP, s.PLATFORM_OVERLAP,
    s.MECHANIC_OVERLAP, s.GAMEPLAY_OVERLAP,
    s.OVERLAP_TIER
FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_SIMILARITY_SCORES s
JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES ga ON s.GAME_A_ID = ga.GAME_ID
JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES gb ON s.GAME_B_ID = gb.GAME_ID
WHERE ga.PUBLISHER_NAME = gb.PUBLISHER_NAME
  AND s.WEIGHTED_OVERLAP >= 0.3;

CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_CATALOG."SP_FIND_CANNIBALIZATION"("THRESHOLD" FLOAT DEFAULT 0.4)
RETURNS TABLE ("GAME_A" VARCHAR, "GAME_B" VARCHAR, "PUBLISHER" VARCHAR, "WEIGHTED_OVERLAP" FLOAT, "GENRE_OVERLAP" FLOAT, "PLATFORM_OVERLAP" FLOAT, "OVERLAP_TIER" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    LET res RESULTSET := (
        SELECT
            s.GAME_A_NAME AS GAME_A,
            s.GAME_B_NAME AS GAME_B,
            ga.PUBLISHER_NAME AS PUBLISHER,
            s.WEIGHTED_OVERLAP,
            s.GENRE_OVERLAP,
            s.PLATFORM_OVERLAP,
            s.OVERLAP_TIER
        FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_SIMILARITY_SCORES s
        JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES ga ON s.GAME_A_ID = ga.GAME_ID
        JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES gb ON s.GAME_B_ID = gb.GAME_ID
        WHERE ga.PUBLISHER_NAME = gb.PUBLISHER_NAME
          AND s.WEIGHTED_OVERLAP >= :THRESHOLD
        ORDER BY s.WEIGHTED_OVERLAP DESC
    );
    RETURN TABLE(res);
END';

CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_SALES.MONTHLY_REVENUE (
	TITLE_ID,
	REVENUE_MONTH,
	MONTHLY_INCOME,
	CUMULATIVE_INCOME,
	REVENUE_SOURCE
) COMMENT = 'Per-title monthly revenue by monetization type, derived from DIGITAL_PRODUCT_TRANSACTIONS and title-specific SUBSCRIPTION_CHARGES. REVENUE_SOURCE is the REVENUE_TYPES.MONETIZATION_TYPE. CUMULATIVE_INCOME is the running total per title through the month.'
AS
WITH by_category AS (
    SELECT dp.TITLE_ID, DATE_TRUNC('MONTH', dpt.TRANSACTION_TIMESTAMP)::DATE AS REVENUE_MONTH,
           rt.MONETIZATION_TYPE AS REVENUE_SOURCE, SUM(dpt.GROSS_REVENUE) AS MONTHLY_INCOME
    FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS dpt
    JOIN ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS dp ON dpt.DIGITAL_PRODUCT_ID = dp.DIGITAL_PRODUCT_ID
    JOIN ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES rt ON dp.CATEGORY_ID = rt.CATEGORY_ID
    GROUP BY 1, 2, 3
    UNION ALL
    SELECT sp.GAME_ID, DATE_TRUNC('MONTH', sc.CHARGE_TIMESTAMP)::DATE, 'SUBSCRIPTION', SUM(sc.GROSS_REVENUE)
    FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES sc
    JOIN ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_PLANS sp ON sc.PLAN_ID = sp.PLAN_ID
    WHERE sp.GAME_ID IS NOT NULL
    GROUP BY 1, 2
), month_totals AS (
    SELECT TITLE_ID, REVENUE_MONTH, SUM(MONTHLY_INCOME) AS MONTH_TOTAL
    FROM by_category GROUP BY TITLE_ID, REVENUE_MONTH
), cumulative AS (
    SELECT TITLE_ID, REVENUE_MONTH,
           SUM(MONTH_TOTAL) OVER (PARTITION BY TITLE_ID ORDER BY REVENUE_MONTH) AS CUMULATIVE_INCOME
    FROM month_totals
)
SELECT b.TITLE_ID, b.REVENUE_MONTH, b.MONTHLY_INCOME, c.CUMULATIVE_INCOME, b.REVENUE_SOURCE
FROM by_category b JOIN cumulative c USING (TITLE_ID, REVENUE_MONTH);

CREATE OR REPLACE DYNAMIC TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_REVENUE (
	TITLE_ID,
	INCOME
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = COMPUTE_WH
AS
SELECT TITLE_ID, SUM(MONTHLY_INCOME) AS INCOME
FROM ONTOLOGY_DEMO.GAME_SALES.MONTHLY_REVENUE
GROUP BY TITLE_ID;

CREATE OR REPLACE DYNAMIC TABLE ONTOLOGY_DEMO.GAME_SALES.QUARTERLY_REVENUE (
	TITLE_ID,
	REVENUE_YEAR,
	REVENUE_QUARTER,
	QUARTERLY_INCOME,
	CUMULATIVE_INCOME
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = COMPUTE_WH
AS
SELECT TITLE_ID,
       YEAR(REVENUE_MONTH) AS REVENUE_YEAR,
       QUARTER(REVENUE_MONTH) AS REVENUE_QUARTER,
       SUM(MONTHLY_INCOME) AS QUARTERLY_INCOME,
       MAX(CUMULATIVE_INCOME) AS CUMULATIVE_INCOME
FROM ONTOLOGY_DEMO.GAME_SALES.MONTHLY_REVENUE
GROUP BY TITLE_ID, YEAR(REVENUE_MONTH), QUARTER(REVENUE_MONTH);

CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_SALES.VW_PLATFORM_EXCLUSIVITY (
	TITLE_ID,
	TITLE_NAME,
	INCOME,
	PLATFORM_ID,
	PLATFORM_NAME,
	IS_EXCLUSIVE,
	EXCLUSIVITY_TYPE,
	EXCLUSIVE_START,
	EXCLUSIVE_END,
	EXCLUSIVITY_NOTE,
	IS_CURRENTLY_EXCLUSIVE
) AS
SELECT
    t.TITLE_ID, t.TITLE_NAME, gr.INCOME,
    p.PLATFORM_ID, p.PLATFORM_NAME,
    gp.IS_EXCLUSIVE,
    gp.EXCLUSIVITY_TYPE,
    gp.EXCLUSIVE_START,
    gp.EXCLUSIVE_END,
    gp.EXCLUSIVITY_NOTE,
    CASE
        WHEN gp.EXCLUSIVITY_TYPE = 'PERMANENT' THEN TRUE
        WHEN gp.EXCLUSIVITY_TYPE = 'TIMED' AND gp.EXCLUSIVE_END >= CURRENT_DATE() THEN TRUE
        ELSE FALSE
    END AS IS_CURRENTLY_EXCLUSIVE
FROM ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS gp
JOIN ONTOLOGY_DEMO.GAME_SALES.TITLES t ON gp.TITLE_ID = t.TITLE_ID
JOIN ONTOLOGY_DEMO.GAME_SALES.PLATFORMS p ON gp.PLATFORM_ID = p.PLATFORM_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_SALES.GAME_REVENUE gr ON t.TITLE_ID = gr.TITLE_ID
WHERE gp.IS_EXCLUSIVE = 'Y';
