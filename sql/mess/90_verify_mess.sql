-- 90_verify_mess.sql
-- Read-only checks after RUN_ALL.sql. Each query returns one row; every *_OK column should be TRUE.
-- Query 3 is also the reference answer an ontology-backed agent must reproduce: revenue per CATALOG game,
-- resolved through the key hierarchy strong (TITLES.CATALOG_GAME_ID) -> medium (TITLE_CODE_XREF) ->
-- weak (normalized title name + release year).

-- 1. Mess is present
SELECT
    (SELECT COUNT(*) FROM ONTOLOGY_DEMO.INFORMATION_SCHEMA.TABLES
      WHERE TABLE_SCHEMA = 'GAME_CATALOG' AND TABLE_NAME IN ('DEVELOPERS','PUBLISHERS','FRANCHISES','GAME_SEQUELS')) = 0 AS C1_TABLES_DROPPED_OK,
    (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.TITLES t JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
      ON g.GAME_ID = t.CATALOG_GAME_ID WHERE g.GAME_NAME <> t.TITLE_NAME) > 0 AS C2_NAMES_DIFFER_OK,
    (SELECT COUNT_IF(CATALOG_GAME_ID IS NULL) FROM ONTOLOGY_DEMO.GAME_SALES.TITLES) AS C3_TITLES_WITHOUT_CATALOG_ID,
    (SELECT COUNT_IF(TITLE_ID IS NULL) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS) AS C3_TXNS_WITHOUT_TITLE,
    (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.TITLE_CODE_XREF) AS C45_XREF_ROWS,
    (SELECT COUNT(DISTINCT REGION) FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS WHERE REGION LIKE 'SIE%') = 5 AS C6_REGIONS_OK,
    (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES) = 13 AS C7_REVENUE_TYPES_OK;

-- 2. Lossless: totals and catalog names unchanged versus CLEAN_BASELINE
SELECT
    (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS)
      = (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_DIGITAL_PRODUCT_TRANSACTIONS) AS DIGITAL_TOTAL_OK,
    (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS)
      = (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_HARDWARE_SALES_TRANSACTIONS) AS HARDWARE_TOTAL_OK,
    (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES)
      = (SELECT ROUND(SUM(GROSS_REVENUE), 2) FROM ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_SUBSCRIPTION_CHARGES) AS SUBSCRIPTION_TOTAL_OK,
    (SELECT COUNT(*) FROM (
        SELECT g.GAME_ID, d.DEVELOPER_NAME, p.PUBLISHER_NAME, f.FRANCHISE_NAME
        FROM ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAMES g
        JOIN ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_DEVELOPERS d ON d.DEVELOPER_ID = g.DEVELOPER_ID
        JOIN ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_FRANCHISES gf ON gf.GAME_ID = g.GAME_ID
        JOIN ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_FRANCHISES f ON f.FRANCHISE_ID = gf.FRANCHISE_ID
        JOIN ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_PUBLISHERS p ON p.PUBLISHER_ID = f.PUBLISHER_ID
        MINUS
        SELECT GAME_ID, DEVELOPER_NAME, PUBLISHER_NAME, FRANCHISE_NAME FROM ONTOLOGY_DEMO.GAME_CATALOG.GAMES)) = 0 AS CATALOG_NAMES_OK,
    (SELECT COUNT(*) FROM (
        SELECT GAME_ID, SEQUEL_OF_GAME_ID, RELATIONSHIP_TYPE FROM ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_SEQUELS
        MINUS
        SELECT GAME_ID, RELATED_GAME_ID, RELATIONSHIP_TYPE FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES
        WHERE RELATED_GAME_ID IS NOT NULL)) = 0 AS SEQUELS_OK;

-- 3. Answerable the hard way: revenue per catalog game equals the clean answer for every game
WITH title_to_game AS (
    SELECT t.TITLE_ID,
           COALESCE(t.CATALOG_GAME_ID, x.CATALOG_GAME_ID, w.GAME_ID) AS GAME_ID,
           CASE WHEN t.CATALOG_GAME_ID IS NOT NULL THEN 'STRONG'
                WHEN x.CATALOG_GAME_ID IS NOT NULL THEN 'MEDIUM'
                WHEN w.GAME_ID IS NOT NULL THEN 'WEAK' END AS LINK
    FROM ONTOLOGY_DEMO.GAME_SALES.TITLES t
    LEFT JOIN (SELECT TITLE_ID, MIN(CATALOG_GAME_ID) AS CATALOG_GAME_ID
               FROM ONTOLOGY_DEMO.GAME_SALES.TITLE_CODE_XREF GROUP BY TITLE_ID) x ON x.TITLE_ID = t.TITLE_ID
    LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMES w
      ON LOWER(TRANSLATE(w.GAME_NAME, 'ōöéü', 'ooeu')) = LOWER(t.TITLE_NAME)
     AND YEAR(w.RELEASE_DATE) = YEAR(TO_DATE(t.RELEASE_DATE, 'YYYYMMDD'))
), revenue AS (
    SELECT tg.GAME_ID, SUM(dpt.GROSS_REVENUE) AS INCOME
    FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS dpt
    JOIN ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS dp ON dp.DIGITAL_PRODUCT_ID = dpt.DIGITAL_PRODUCT_ID
    JOIN title_to_game tg ON tg.TITLE_ID = COALESCE(dpt.TITLE_ID, dp.TITLE_ID)
    GROUP BY tg.GAME_ID
)
SELECT
    (SELECT COUNT(*) FROM title_to_game WHERE GAME_ID IS NULL) = 0 AS ALL_TITLES_RESOLVED_OK,
    (SELECT LISTAGG(LINK || ':' || N, ', ') FROM (SELECT LINK, COUNT(*) N FROM title_to_game GROUP BY LINK)) AS LINKS_USED,
    (SELECT COUNT(*) FROM ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_REVENUE c
       FULL JOIN revenue r ON r.GAME_ID = c.GAME_ID
      WHERE ROUND(COALESCE(r.INCOME, 0), 2) <> ROUND(COALESCE(c.INCOME, 0), 2)) = 0 AS REVENUE_PER_GAME_OK;
