-- 20_c1_overloaded_catalog.sql
-- CHALLENGE 1: Overloaded tables (one table -> many ontology classes). GAME_CATALOG only.
--   GAMES               = Game + Developer + Publisher + Franchise
--   GAME_FRANCHISES     = Franchise membership + Franchise + sequel graph (merge-sequels plan, adapted)
--   STUDIO_ACQUISITIONS = Acquisition + Studio
-- Then DEVELOPERS, PUBLISHERS, FRANCHISES and GAME_SEQUELS are dropped: those classes only live inside other rows.
-- Lossless: every game has exactly one developer and one franchise row (checked 2026-10-13).
EXECUTE IMMEDIATE $$
BEGIN
    -- GAMES absorbs Developer, Publisher (via franchise) and Franchise
    ALTER TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAMES ADD COLUMN
        DEVELOPER_NAME VARCHAR COMMENT 'Studio that built the game',
        DEVELOPER_IS_INDIE BOOLEAN,
        PUBLISHER_ID NUMBER(38,0),
        PUBLISHER_NAME VARCHAR,
        PUBLISHER_HQ VARCHAR,
        FRANCHISE_NAME VARCHAR;

    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
    SET DEVELOPER_NAME = d.DEVELOPER_NAME,
        DEVELOPER_IS_INDIE = d.IS_INDIE
    FROM ONTOLOGY_DEMO.GAME_CATALOG.DEVELOPERS d
    WHERE g.DEVELOPER_ID = d.DEVELOPER_ID;

    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
    SET PUBLISHER_ID = f.PUBLISHER_ID,
        PUBLISHER_NAME = p.PUBLISHER_NAME,
        PUBLISHER_HQ = p.HEADQUARTERS,
        FRANCHISE_NAME = f.FRANCHISE_NAME
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES gf
    JOIN ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES f ON f.FRANCHISE_ID = gf.FRANCHISE_ID
    JOIN ONTOLOGY_DEMO.GAME_CATALOG.PUBLISHERS p ON p.PUBLISHER_ID = f.PUBLISHER_ID
    WHERE g.GAME_ID = gf.GAME_ID;

    -- GAME_FRANCHISES absorbs Franchise and the sequel links (GAME_SEQUELS)
    ALTER TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES ADD COLUMN
        FRANCHISE_NAME VARCHAR,
        FIRST_RELEASE_YEAR NUMBER(38,0),
        PUBLISHER_ID NUMBER(38,0),
        RELATED_GAME_ID NUMBER(38,0) COMMENT 'Game this one derives from; may be in another franchise',
        RELATIONSHIP_TYPE VARCHAR DEFAULT 'original' COMMENT 'original, sequel, prequel, spinoff, remake, spiritual_successor';

    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES gf
    SET FRANCHISE_NAME = f.FRANCHISE_NAME,
        FIRST_RELEASE_YEAR = f.FIRST_RELEASE_YEAR,
        PUBLISHER_ID = f.PUBLISHER_ID
    FROM ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES f
    WHERE gf.FRANCHISE_ID = f.FRANCHISE_ID;

    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES gf
    SET RELATED_GAME_ID = s.SEQUEL_OF_GAME_ID,
        RELATIONSHIP_TYPE = s.RELATIONSHIP_TYPE
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_SEQUELS s
    WHERE gf.GAME_ID = s.GAME_ID;

    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES
    SET RELATIONSHIP_TYPE = 'original' WHERE RELATED_GAME_ID IS NULL;

    -- STUDIO_ACQUISITIONS absorbs the studio name (only place left that names acquired studios)
    ALTER TABLE ONTOLOGY_DEMO.GAME_CATALOG.STUDIO_ACQUISITIONS ADD COLUMN STUDIO_NAME VARCHAR;
    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.STUDIO_ACQUISITIONS sa
    SET STUDIO_NAME = d.DEVELOPER_NAME
    FROM ONTOLOGY_DEMO.GAME_CATALOG.DEVELOPERS d
    WHERE sa.DEVELOPER_ID = d.DEVELOPER_ID;

    DROP TABLE ONTOLOGY_DEMO.GAME_CATALOG.DEVELOPERS;
    DROP TABLE ONTOLOGY_DEMO.GAME_CATALOG.PUBLISHERS;
    DROP TABLE ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES;
    DROP TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAME_SEQUELS;

    RETURN 'C1 applied';
END;
$$;
