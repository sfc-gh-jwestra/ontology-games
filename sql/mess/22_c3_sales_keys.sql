-- 22_c3_sales_keys.sql
-- CHALLENGE 3: Identity resolution with imperfect keys (Sales -> Catalog).
-- Sales gets its OWN key: TITLE_ID = 5000 + rank by release date (no longer equals catalog GAME_ID).
--   Strong : TITLES.CATALOG_GAME_ID           NULL for every 7th title, plus 631 and 639
--   Medium : TITLE_CODE_XREF.CATALOG_GAME_ID  (23_c45) - missing for 631 and 639
--   Weak   : title name + release year         only path for 631 ('Ghost of Yotei') and 639 (JP-format date, 24_c6)
-- DIGITAL_PRODUCT_TRANSACTIONS.TITLE_ID is NULL for every 10th transaction; recover it via DIGITAL_PRODUCT_ID.
EXECUTE IMMEDIATE $$
BEGIN
    CREATE OR REPLACE TEMPORARY TABLE ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP AS
    SELECT TITLE_ID AS OLD_ID,
           5000 + ROW_NUMBER() OVER (ORDER BY RELEASE_DATE, TITLE_ID) AS NEW_ID
    FROM ONTOLOGY_DEMO.GAME_SALES.TITLES;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.TITLES ADD COLUMN
        CATALOG_GAME_ID NUMBER(38,0) COMMENT 'Game id in the catalog system, when known';

    UPDATE ONTOLOGY_DEMO.GAME_SALES.TITLES t
    SET CATALOG_GAME_ID = IFF(MOD(m.NEW_ID, 7) = 0 OR m.OLD_ID IN (631, 639), NULL, m.OLD_ID),
        TITLE_ID = m.NEW_ID
    FROM ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP m WHERE t.TITLE_ID = m.OLD_ID;

    -- Remap every Sales reference to the new key
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS RENAME COLUMN GAME_ID TO TITLE_ID;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS x SET TITLE_ID = m.NEW_ID
    FROM ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP m WHERE x.TITLE_ID = m.OLD_ID;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS RENAME COLUMN GAME_ID TO TITLE_ID;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS x SET TITLE_ID = m.NEW_ID
    FROM ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP m WHERE x.TITLE_ID = m.OLD_ID;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_MONETIZATION RENAME COLUMN GAME_ID TO TITLE_ID;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.GAME_MONETIZATION x SET TITLE_ID = m.NEW_ID
    FROM ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP m WHERE x.TITLE_ID = m.OLD_ID;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS RENAME COLUMN GAME_ID TO TITLE_ID;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS x
    SET TITLE_ID = IFF(MOD(x.TRANSACTION_ID, 10) = 0, NULL, m.NEW_ID)
    FROM ONTOLOGY_DEMO.GAME_SALES.TMP_TITLE_MAP m WHERE x.TITLE_ID = m.OLD_ID;

    RETURN 'C3 applied';
END;
$$;
