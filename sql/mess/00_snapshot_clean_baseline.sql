-- 00_snapshot_clean_baseline.sql
-- Zero-copy clones the clean tables that the mess scripts change, into ONTOLOGY_DEMO.CLEAN_BASELINE.
-- Run once on CLEAN data (and again after SP_GENERATE_SALES regenerates data via 99_restore_clean.sql).
-- Guard: refuses to run if the live tables are already messy (GAME_CATALOG.DEVELOPERS was dropped by 20_c1).
EXECUTE IMMEDIATE $$
DECLARE
    is_clean INTEGER;
BEGIN
    SELECT COUNT(*) INTO :is_clean FROM ONTOLOGY_DEMO.INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = 'GAME_CATALOG' AND TABLE_NAME = 'DEVELOPERS';
    IF (is_clean = 0) THEN
        RETURN 'ABORTED: live tables are already messy. Run 99_restore_clean.sql first.';
    END IF;

    CREATE SCHEMA IF NOT EXISTS ONTOLOGY_DEMO.CLEAN_BASELINE
        COMMENT = 'Clean snapshot used by sql/mess/10_restore_from_baseline.sql. Do not edit.';

    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAMES               CLONE ONTOLOGY_DEMO.GAME_CATALOG.GAMES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_DEVELOPERS          CLONE ONTOLOGY_DEMO.GAME_CATALOG.DEVELOPERS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_PUBLISHERS          CLONE ONTOLOGY_DEMO.GAME_CATALOG.PUBLISHERS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_FRANCHISES          CLONE ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_FRANCHISES     CLONE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_SEQUELS        CLONE ONTOLOGY_DEMO.GAME_CATALOG.GAME_SEQUELS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_STUDIO_ACQUISITIONS CLONE ONTOLOGY_DEMO.GAME_CATALOG.STUDIO_ACQUISITIONS;

    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAMES                        CLONE ONTOLOGY_DEMO.GAME_SALES.GAMES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_PLATFORMS                    CLONE ONTOLOGY_DEMO.GAME_SALES.PLATFORMS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_PLATFORMS               CLONE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_MONETIZATION            CLONE ONTOLOGY_DEMO.GAME_SALES.GAME_MONETIZATION;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_CUSTOMER_ACCOUNTS            CLONE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_DIGITAL_PRODUCTS             CLONE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_DIGITAL_PRODUCT_TRANSACTIONS CLONE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_HARDWARE_SALES_TRANSACTIONS  CLONE ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_SUBSCRIPTION_CHARGES         CLONE ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_REVENUE_CATEGORIES           CLONE ONTOLOGY_DEMO.GAME_SALES.REVENUE_CATEGORIES;
    -- Clean revenue answer key, used by the verification queries.
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_REVENUE AS
        SELECT GAME_ID, INCOME FROM ONTOLOGY_DEMO.GAME_SALES.GAME_REVENUE;

    RETURN 'Snapshot complete: 18 tables in ONTOLOGY_DEMO.CLEAN_BASELINE';
END;
$$;
