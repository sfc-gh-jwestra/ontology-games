-- 10_restore_from_baseline.sql
-- Puts the 17 affected tables back to their clean shape and data from ONTOLOGY_DEMO.CLEAN_BASELINE,
-- and drops the tables that only exist in the messy shape. Makes the mess scripts re-runnable.
-- Dependent views / DTs / procs are NOT touched here: RUN_ALL.sql redeploys the messy versions (30_*),
-- 99_restore_clean.sql redeploys the clean versions.
EXECUTE IMMEDIATE $$
BEGIN
    -- Messy-only tables
    DROP TABLE IF EXISTS ONTOLOGY_DEMO.GAME_SALES.TITLES;
    DROP TABLE IF EXISTS ONTOLOGY_DEMO.GAME_SALES.TITLE_CODE_XREF;
    DROP TABLE IF EXISTS ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES;

    -- GAME_CATALOG
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAMES               CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAMES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.DEVELOPERS          CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_DEVELOPERS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.PUBLISHERS          CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_PUBLISHERS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES          CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_FRANCHISES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES     CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_FRANCHISES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAME_SEQUELS        CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_GAME_SEQUELS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_CATALOG.STUDIO_ACQUISITIONS CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.CAT_STUDIO_ACQUISITIONS;

    -- GAME_SALES
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.GAMES                        CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAMES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.PLATFORMS                    CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_PLATFORMS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS               CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_PLATFORMS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_MONETIZATION            CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAME_MONETIZATION;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS            CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_CUSTOMER_ACCOUNTS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS             CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_DIGITAL_PRODUCTS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_DIGITAL_PRODUCT_TRANSACTIONS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS  CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_HARDWARE_SALES_TRANSACTIONS;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES         CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_SUBSCRIPTION_CHARGES;
    CREATE OR REPLACE TABLE ONTOLOGY_DEMO.GAME_SALES.REVENUE_CATEGORIES           CLONE ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_REVENUE_CATEGORIES;

    RETURN 'Restored 17 tables from CLEAN_BASELINE';
END;
$$;
