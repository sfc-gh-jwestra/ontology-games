-- 25_c7_overloaded_names.sql
-- CHALLENGE 7: Overloaded column names (same name, different meaning).
--   STATUS            : Catalog GAMES.STATUS             = lifecycle   (RELEASED, REMASTERED, DELISTED)
--                       Sales CUSTOMER_ACCOUNTS.STATUS   = account     (A active, S suspended, C closed; replaces IS_ACTIVE)
--                       Sales DIGITAL_PRODUCTS.STATUS    = store listing (LIVE, DELISTED)
--   MONETIZATION_TYPE : MONETIZATION_TYPES (both systems) = business-model tag on a game, nothing priced
--                       Sales REVENUE_TYPES.MONETIZATION_TYPE (was REVENUE_CATEGORIES.CATEGORY_NAME) = what was sold
--   Existing traps documented, not changed: DIGITAL_PRODUCT_TRANSACTIONS.NET_DEVELOPER_REVENUE (publisher share),
--   ENGINES.DEVELOPER_COMPANY (engine vendor), GENRE_CATEGORY_MAP.CATEGORY_NAME vs REVENUE_TYPES.CATEGORY_GROUP.
-- Must run after 20_c1 and 22_c3.
EXECUTE IMMEDIATE $$
BEGIN
    -- Catalog: game lifecycle status
    ALTER TABLE ONTOLOGY_DEMO.GAME_CATALOG.GAMES ADD COLUMN STATUS VARCHAR;
    UPDATE ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
    SET STATUS = CASE
        WHEN g.GAME_ID = 616 THEN 'DELISTED'
        WHEN gf.RELATIONSHIP_TYPE = 'remake' OR g.GAME_NAME ILIKE '%remaster%' THEN 'REMASTERED'
        ELSE 'RELEASED' END
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES gf
    WHERE gf.GAME_ID = g.GAME_ID;

    -- Sales: account status code replaces the boolean
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS ADD COLUMN STATUS VARCHAR(1);
    UPDATE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS
    SET STATUS = CASE WHEN NOT IS_ACTIVE THEN 'C' WHEN MOD(CUSTOMER_ID, 97) = 0 THEN 'S' ELSE 'A' END;
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS DROP COLUMN IS_ACTIVE;

    -- Sales: store listing status
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS ADD COLUMN STATUS VARCHAR;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS dp
    SET STATUS = IFF(t.TITLE_NAME = 'Concord', 'DELISTED', 'LIVE')
    FROM ONTOLOGY_DEMO.GAME_SALES.TITLES t
    WHERE t.TITLE_ID = dp.TITLE_ID;

    -- Sales: what was sold is now also called a "monetization type"
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.REVENUE_CATEGORIES RENAME TO ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES;
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES RENAME COLUMN CATEGORY_NAME TO MONETIZATION_TYPE;

    RETURN 'C7 applied';
END;
$$;
