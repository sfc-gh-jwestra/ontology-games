-- 24_c6_codes.sql
-- CHALLENGE 6: Divergent code and value conventions.
--   Region      : CUSTOMER_ACCOUNTS.REGION -> SIE codes (SIEA, SIEE, SIEJ, SIEAP, SIELA)
--                 HARDWARE_SALES_TRANSACTIONS.REGION keeps NA / EU / JP / ASIA / LATAM (two conventions in Sales)
--   Platform    : PLATFORMS gets PLATFORM_CODE (PS5, PS4, PC ...) next to the store-style PLATFORM_NAME (21_c2)
--   Exclusivity : Sales GAME_PLATFORMS.IS_EXCLUSIVE BOOLEAN -> VARCHAR 'Y' / 'N' (Catalog stays BOOLEAN)
--   Release     : TITLES.RELEASE_DATE DATE -> VARCHAR 'YYYYMMDD'; 3 titles hold the JP date (one day earlier)
-- Must run after 22_c3.
EXECUTE IMMEDIATE $$
BEGIN
    UPDATE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS
    SET REGION = DECODE(REGION, 'NA', 'SIEA', 'EU', 'SIEE', 'JP', 'SIEJ', 'ASIA', 'SIEAP', 'LATAM', 'SIELA', REGION);

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.PLATFORMS ADD COLUMN PLATFORM_CODE VARCHAR;
    UPDATE ONTOLOGY_DEMO.GAME_SALES.PLATFORMS p
    SET PLATFORM_CODE = v.CODE
    FROM (SELECT column1 AS PLATFORM_ID, column2 AS CODE FROM VALUES
            (1, 'AND'), (2, 'NDS'), (3, 'XB1'), (4, 'IOS'), (5, 'PS3'), (6, 'PC'), (7, 'X360'), (8, 'PS4'),
            (101, 'PS5'), (102, 'XBSX'), (103, 'NSW'), (104, 'STD'), (201, '3DS'), (202, 'PSV'), (203, 'NES'),
            (204, 'SNES'), (205, 'N64'), (206, 'GCN'), (207, 'WII'), (208, 'PS2')) v
    WHERE p.PLATFORM_ID = v.PLATFORM_ID;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS ADD COLUMN IS_EXCLUSIVE_YN VARCHAR(1);
    UPDATE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS SET IS_EXCLUSIVE_YN = IFF(IS_EXCLUSIVE, 'Y', 'N');
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS DROP COLUMN IS_EXCLUSIVE;
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS RENAME COLUMN IS_EXCLUSIVE_YN TO IS_EXCLUSIVE;

    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.TITLES ADD COLUMN RELEASE_DATE_TXT VARCHAR(8);
    UPDATE ONTOLOGY_DEMO.GAME_SALES.TITLES t
    SET RELEASE_DATE_TXT = TO_VARCHAR(IFF(m.GAME_ID IN (405, 639, 652), DATEADD(day, -1, t.RELEASE_DATE), t.RELEASE_DATE), 'YYYYMMDD')
    FROM (SELECT GAME_ID, 5000 + ROW_NUMBER() OVER (ORDER BY RELEASE_DATE, GAME_ID) AS TITLE_ID
          FROM ONTOLOGY_DEMO.CLEAN_BASELINE.SAL_GAMES) m
    WHERE t.TITLE_ID = m.TITLE_ID;
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.TITLES DROP COLUMN RELEASE_DATE;
    ALTER TABLE ONTOLOGY_DEMO.GAME_SALES.TITLES RENAME COLUMN RELEASE_DATE_TXT TO RELEASE_DATE;

    RETURN 'C6 applied';
END;
$$;
