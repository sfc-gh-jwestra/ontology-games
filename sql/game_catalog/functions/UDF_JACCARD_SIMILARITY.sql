CREATE OR REPLACE FUNCTION ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY("SET_A" ARRAY, "SET_B" ARRAY)
RETURNS FLOAT
LANGUAGE SQL
AS '
    CASE
        WHEN (SET_A IS NULL OR ARRAY_SIZE(SET_A) = 0) AND (SET_B IS NULL OR ARRAY_SIZE(SET_B) = 0) THEN NULL
        WHEN SET_A IS NULL OR ARRAY_SIZE(SET_A) = 0 THEN 0.0
        WHEN SET_B IS NULL OR ARRAY_SIZE(SET_B) = 0 THEN 0.0
        ELSE ARRAY_SIZE(ARRAY_INTERSECTION(SET_A, SET_B))::FLOAT
             / ARRAY_SIZE(ARRAY_DISTINCT(ARRAY_CAT(SET_A, SET_B)))::FLOAT
    END
';
