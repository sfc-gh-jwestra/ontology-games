CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_CATALOG.VW_GAME_OVERLAP_MATRIX (
	GAME_A_ID,
	GAME_A_NAME,
	GAME_B_ID,
	GAME_B_NAME,
	GENRE_OVERLAP,
	PLATFORM_OVERLAP,
	MECHANIC_OVERLAP,
	GAMEPLAY_OVERLAP,
	CONTEXT_OVERLAP,
	POV_MATCH,
	NARRATIVE_MATCH
) COMMENT = 'The table contains records of game overlap matrices, specifically comparisons between different games. Each record represents a pair of games and includes details about their shared genres, platforms, mechanics, gameplay, and other characteristics.'
AS
WITH game_genres AS (
    SELECT GAME_ID, ARRAY_AGG(DISTINCT GENRE) AS GENRES
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_GENRE_CLASSIFICATION
    WHERE MATCH_STATUS = 'FULL'
    GROUP BY GAME_ID
), game_plats AS (
    SELECT gp.GAME_ID, ARRAY_AGG(DISTINCT p.PLATFORM_NAME) AS PLATFORMS
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_PLATFORMS gp
    JOIN ONTOLOGY_DEMO.GAME_CATALOG.PLATFORMS p ON gp.PLATFORM_ID = p.PLATFORM_ID
    GROUP BY gp.GAME_ID
), profiles AS (
    SELECT GAME_ID, GAME_NAME, POV, NARRATIVE,
           GAMEPLAY_TYPES AS GAMEPLAY_ARR,
           MECHANICS AS MECHANIC_ARR,
           CONTEXTS AS CONTEXT_ARR
    FROM ONTOLOGY_DEMO.GAME_CATALOG.VW_GAME_PROFILE
)
SELECT
    a.GAME_ID AS GAME_A_ID, a.GAME_NAME AS GAME_A_NAME,
    b.GAME_ID AS GAME_B_ID, b.GAME_NAME AS GAME_B_NAME,
    ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY(ga.GENRES, gb.GENRES) AS GENRE_OVERLAP,
    ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY(pa.PLATFORMS, pb.PLATFORMS) AS PLATFORM_OVERLAP,
    ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY(a.MECHANIC_ARR, b.MECHANIC_ARR) AS MECHANIC_OVERLAP,
    ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY(a.GAMEPLAY_ARR, b.GAMEPLAY_ARR) AS GAMEPLAY_OVERLAP,
    ONTOLOGY_DEMO.GAME_CATALOG.UDF_JACCARD_SIMILARITY(a.CONTEXT_ARR, b.CONTEXT_ARR) AS CONTEXT_OVERLAP,
    CASE WHEN a.POV = b.POV AND a.POV IS NOT NULL THEN 1.0 ELSE 0.0 END AS POV_MATCH,
    CASE WHEN a.NARRATIVE = b.NARRATIVE AND a.NARRATIVE IS NOT NULL THEN 1.0 ELSE 0.0 END AS NARRATIVE_MATCH
FROM profiles a
JOIN profiles b ON a.GAME_ID < b.GAME_ID
LEFT JOIN game_genres ga ON a.GAME_ID = ga.GAME_ID
LEFT JOIN game_genres gb ON b.GAME_ID = gb.GAME_ID
LEFT JOIN game_plats pa ON a.GAME_ID = pa.GAME_ID
LEFT JOIN game_plats pb ON b.GAME_ID = pb.GAME_ID;
