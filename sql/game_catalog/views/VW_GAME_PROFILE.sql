CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_CATALOG.VW_GAME_PROFILE (
	GAME_ID,
	GAME_NAME,
	POV,
	NARRATIVE,
	GAMEPLAY_TYPES,
	MECHANICS,
	CONTEXTS,
	MAX_PLAYER_COUNT,
	HAS_ONLINE_MODE
) AS
SELECT
    g.GAME_ID,
    g.GAME_NAME,
    g.POV,
    ns.STRUCTURE_NAME AS NARRATIVE,
    ARRAY_AGG(DISTINCT gt.GAMEPLAY_TYPE_NAME) AS GAMEPLAY_TYPES,
    ARRAY_AGG(DISTINCT m.MECHANIC_NAME) AS MECHANICS,
    ARRAY_AGG(DISTINCT c.CONTEXT_NAME) AS CONTEXTS,
    MAX(gm.MAX_PLAYERS) AS MAX_PLAYER_COUNT,
    BOOLOR_AGG(gm.ONLINE_REQUIRED) AS HAS_ONLINE_MODE
FROM ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.NARRATIVE_STRUCTURES ns ON g.NARRATIVE_STRUCTURE_ID = ns.STRUCTURE_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_GAMEPLAY gg ON g.GAME_ID = gg.GAME_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAMEPLAY_TYPES gt ON gg.GAMEPLAY_TYPE_ID = gt.GAMEPLAY_TYPE_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_MECHANICS gmc ON g.GAME_ID = gmc.GAME_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.MECHANICS m ON gmc.MECHANIC_ID = m.MECHANIC_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_CONTEXTS gc ON g.GAME_ID = gc.GAME_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.CONTEXTS c ON gc.CONTEXT_ID = c.CONTEXT_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_MODES gm ON g.GAME_ID = gm.GAME_ID
GROUP BY g.GAME_ID, g.GAME_NAME, g.POV, ns.STRUCTURE_NAME;
