create or replace view ONTOLOGY_DEMO.GAME_CATALOG.VW_GAME_GENRE_ROLLUP(
	GAME_ID,
	ROLLUP_GENRE,
	ROLLUP_DEPTH
) COMMENT='One row per game per genre it belongs to: each FULL-matched genre plus all its ancestors in the PARENT_GENRE tree. Distinct per (GAME_ID, ROLLUP_GENRE).'
 as
WITH RECURSIVE anc AS (
    SELECT GENRE, GENRE AS ANCESTOR_GENRE
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GENRE_RULES
    UNION ALL
    SELECT a.GENRE, r.PARENT_GENRE
    FROM anc a
    JOIN ONTOLOGY_DEMO.GAME_CATALOG.GENRE_RULES r ON r.GENRE = a.ANCESTOR_GENRE
    WHERE r.PARENT_GENRE IS NOT NULL
)
SELECT DISTINCT c.GAME_ID, a.ANCESTOR_GENRE AS ROLLUP_GENRE, h.DEPTH AS ROLLUP_DEPTH
FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_GENRE_CLASSIFICATION c
JOIN anc a ON a.GENRE = c.GENRE
JOIN ONTOLOGY_DEMO.GAME_CATALOG.VW_GENRE_HIERARCHY h ON h.GENRE = a.ANCESTOR_GENRE
WHERE c.MATCH_STATUS = 'FULL'
  AND h.PARENT_GENRE IS NOT NULL;
