create or replace dynamic table ONTOLOGY_DEMO.GAME_CATALOG.GAME_SIMILARITY_SCORES(
	GAME_A_ID,
	GAME_A_NAME,
	GAME_B_ID,
	GAME_B_NAME,
	GENRE_OVERLAP,
	PLATFORM_OVERLAP,
	MECHANIC_OVERLAP,
	GAMEPLAY_OVERLAP,
	CONTEXT_OVERLAP,
	POV_MATCH,
	NARRATIVE_MATCH,
	WEIGHTED_OVERLAP,
	OVERLAP_TIER
) target_lag = '1 hour' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as
WITH weights AS (
    SELECT
        MAX(CASE WHEN DIMENSION_NAME = 'GENRE' THEN WEIGHT END) AS W_GENRE,
        MAX(CASE WHEN DIMENSION_NAME = 'PLATFORM' THEN WEIGHT END) AS W_PLATFORM,
        MAX(CASE WHEN DIMENSION_NAME = 'MECHANIC' THEN WEIGHT END) AS W_MECHANIC,
        MAX(CASE WHEN DIMENSION_NAME = 'GAMEPLAY' THEN WEIGHT END) AS W_GAMEPLAY,
        MAX(CASE WHEN DIMENSION_NAME = 'CONTEXT' THEN WEIGHT END) AS W_CONTEXT,
        MAX(CASE WHEN DIMENSION_NAME = 'POV' THEN WEIGHT END) AS W_POV,
        MAX(CASE WHEN DIMENSION_NAME = 'NARRATIVE' THEN WEIGHT END) AS W_NARRATIVE
    FROM ONTOLOGY_DEMO.GAME_CATALOG.SIMILARITY_WEIGHTS
), scored AS (
    SELECT
        m.GAME_A_ID, m.GAME_A_NAME, m.GAME_B_ID, m.GAME_B_NAME,
        m.GENRE_OVERLAP, m.PLATFORM_OVERLAP, m.MECHANIC_OVERLAP,
        m.GAMEPLAY_OVERLAP, m.CONTEXT_OVERLAP, m.POV_MATCH, m.NARRATIVE_MATCH,
        (COALESCE(m.GENRE_OVERLAP, 0) * w.W_GENRE
       + COALESCE(m.PLATFORM_OVERLAP, 0) * w.W_PLATFORM
       + COALESCE(m.MECHANIC_OVERLAP, 0) * w.W_MECHANIC
       + COALESCE(m.GAMEPLAY_OVERLAP, 0) * w.W_GAMEPLAY
       + COALESCE(m.CONTEXT_OVERLAP, 0) * w.W_CONTEXT
       + m.POV_MATCH * w.W_POV
       + m.NARRATIVE_MATCH * w.W_NARRATIVE) AS WEIGHTED_OVERLAP
    FROM ONTOLOGY_DEMO.GAME_CATALOG.VW_GAME_OVERLAP_MATRIX m
    CROSS JOIN weights w
)
SELECT
    GAME_A_ID, GAME_A_NAME, GAME_B_ID, GAME_B_NAME,
    GENRE_OVERLAP, PLATFORM_OVERLAP, MECHANIC_OVERLAP,
    GAMEPLAY_OVERLAP, CONTEXT_OVERLAP, POV_MATCH, NARRATIVE_MATCH,
    ROUND(WEIGHTED_OVERLAP, 4) AS WEIGHTED_OVERLAP,
    CASE
        WHEN WEIGHTED_OVERLAP >= 0.6 THEN 'HIGH'
        WHEN WEIGHTED_OVERLAP >= 0.3 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS OVERLAP_TIER
FROM scored;
