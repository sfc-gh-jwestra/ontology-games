create or replace dynamic table ONTOLOGY_DEMO.GAME_CATALOG.GENRE_WHITESPACE_ANALYSIS(
	GENRE_A,
	GENRE_B,
	GAME_COUNT,
	MARKET_STATUS
) target_lag = '1 hour' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as
WITH leaf_genres AS (
    SELECT r.GENRE FROM ONTOLOGY_DEMO.GAME_CATALOG.GENRE_RULES r
    WHERE r.RULE_DEFINITION IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_CATALOG.GENRE_RULES c
                      WHERE c.PARENT_GENRE = r.GENRE)
), disjoint_pairs AS (
    SELECT GENRE AS GENRE_A, TRIM(VALUE::STRING) AS GENRE_B
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GENRE_RULES,
    LATERAL FLATTEN(INPUT => SPLIT(DISJOINT_WITH, ','))
    WHERE DISJOINT_WITH IS NOT NULL AND DISJOINT_WITH != '' AND DISJOINT_WITH != 'None'
), all_pairs AS (
    SELECT a.GENRE AS GENRE_A, b.GENRE AS GENRE_B
    FROM leaf_genres a JOIN leaf_genres b ON a.GENRE < b.GENRE
), valid_pairs AS (
    SELECT ap.* FROM all_pairs ap
    WHERE NOT EXISTS (
        SELECT 1 FROM disjoint_pairs dp
        WHERE (dp.GENRE_A = ap.GENRE_A AND dp.GENRE_B = ap.GENRE_B)
           OR (dp.GENRE_A = ap.GENRE_B AND dp.GENRE_B = ap.GENRE_A)
    )
), game_genre_pairs AS (
    SELECT a.GAME_ID, a.GENRE AS GENRE_A, b.GENRE AS GENRE_B
    FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_GENRE_CLASSIFICATION a
    JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_GENRE_CLASSIFICATION b
      ON a.GAME_ID = b.GAME_ID AND a.GENRE < b.GENRE
    WHERE a.MATCH_STATUS = 'FULL' AND b.MATCH_STATUS = 'FULL'
)
SELECT
    vp.GENRE_A, vp.GENRE_B,
    COUNT(DISTINCT ggp.GAME_ID) AS GAME_COUNT,
    CASE
        WHEN COUNT(DISTINCT ggp.GAME_ID) = 0 THEN 'WHITESPACE'
        WHEN COUNT(DISTINCT ggp.GAME_ID) <= 2 THEN 'UNDERSERVED'
        ELSE 'SERVED'
    END AS MARKET_STATUS
FROM valid_pairs vp
LEFT JOIN game_genre_pairs ggp ON vp.GENRE_A = ggp.GENRE_A AND vp.GENRE_B = ggp.GENRE_B
GROUP BY vp.GENRE_A, vp.GENRE_B;
