CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_CATALOG.SP_CLASSIFICATION_GAP("P_GAME_ID" NUMBER(38,0), "P_GENRE" VARCHAR)
RETURNS TABLE ("CONDITION" VARCHAR, "STATUS" VARCHAR, "DETAILS" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'DECLARE
    res RESULTSET;
BEGIN
    res := (
        SELECT f.VALUE::STRING AS CONDITION, ''MET'' AS STATUS, '''' AS DETAILS
        FROM GAME_GENRE_CLASSIFICATION c,
             LATERAL FLATTEN(input => c.MATCHED_CONDITIONS) f
        WHERE c.GAME_ID = :P_GAME_ID AND c.GENRE = :P_GENRE
        
        UNION ALL
        
        SELECT f.VALUE::STRING, ''MISSING'', ''''
        FROM GAME_GENRE_CLASSIFICATION c,
             LATERAL FLATTEN(input => c.MISSING_CONDITIONS) f
        WHERE c.GAME_ID = :P_GAME_ID AND c.GENRE = :P_GENRE
        
        UNION ALL
        
        SELECT f.VALUE::STRING, ''UNKNOWN'', ''''
        FROM GAME_GENRE_CLASSIFICATION c,
             LATERAL FLATTEN(input => c.UNKNOWN_CONDITIONS) f
        WHERE c.GAME_ID = :P_GAME_ID AND c.GENRE = :P_GENRE
    );
    RETURN TABLE(res);
END';
