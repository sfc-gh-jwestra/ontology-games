CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_CATALOG."SP_FIND_CANNIBALIZATION"("THRESHOLD" FLOAT DEFAULT 0.4)
RETURNS TABLE ("GAME_A" VARCHAR, "GAME_B" VARCHAR, "PUBLISHER" VARCHAR, "WEIGHTED_OVERLAP" FLOAT, "GENRE_OVERLAP" FLOAT, "PLATFORM_OVERLAP" FLOAT, "OVERLAP_TIER" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    LET res RESULTSET := (
        WITH game_publisher AS (
            SELECT DISTINCT g.GAME_ID, g.GAME_NAME, pub.PUBLISHER_NAME
            FROM ONTOLOGY_DEMO.GAME_CATALOG.GAMES g
            JOIN ONTOLOGY_DEMO.GAME_CATALOG.GAME_FRANCHISES gf ON g.GAME_ID = gf.GAME_ID
            JOIN ONTOLOGY_DEMO.GAME_CATALOG.FRANCHISES f ON gf.FRANCHISE_ID = f.FRANCHISE_ID
            JOIN ONTOLOGY_DEMO.GAME_CATALOG.PUBLISHERS pub ON f.PUBLISHER_ID = pub.PUBLISHER_ID
        )
        SELECT
            s.GAME_A_NAME AS GAME_A,
            s.GAME_B_NAME AS GAME_B,
            pa.PUBLISHER_NAME AS PUBLISHER,
            s.WEIGHTED_OVERLAP,
            s.GENRE_OVERLAP,
            s.PLATFORM_OVERLAP,
            s.OVERLAP_TIER
        FROM ONTOLOGY_DEMO.GAME_CATALOG.GAME_SIMILARITY_SCORES s
        JOIN game_publisher pa ON s.GAME_A_ID = pa.GAME_ID
        JOIN game_publisher pb ON s.GAME_B_ID = pb.GAME_ID
        WHERE pa.PUBLISHER_NAME = pb.PUBLISHER_NAME
          AND s.WEIGHTED_OVERLAP >= :THRESHOLD
        ORDER BY s.WEIGHTED_OVERLAP DESC
    );
    RETURN TABLE(res);
END';
