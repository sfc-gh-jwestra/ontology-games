CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_CATALOG()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Synthetic generator step 0: rebuilds GEN_GAME_PROFILE and GEN_PLATFORM_AVAILABILITY from the catalog, and inserts any DIGITAL_PRODUCTS SKUs that are missing (new games, or SKUs that became due as AS_OF_DATE advanced). Existing DIGITAL_PRODUCT_IDs are never changed.'
EXECUTE AS OWNER
AS
$$
DECLARE
  as_of DATE;
  added NUMBER;
BEGIN
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';

  -- Per game: monetization profile (loot_boxes > battle_pass > microtransactions > dlc > premium), launch price, revenue source
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE
  COMMENT = 'Generator input per game: monetization profile, approximate US launch MSRP, and revenue source (BACKUP months or ADD_GAME_TMP actual estimate). Rebuilt by SP_GEN_CATALOG.'
  AS
  WITH tags AS (
    SELECT gm.GAME_ID, ARRAY_AGG(mt.MONETIZATION_NAME) t
    FROM ONTOLOGY_DEMO.GAME_SALES.GAME_MONETIZATION gm JOIN ONTOLOGY_DEMO.GAME_SALES.MONETIZATION_TYPES mt ON gm.MONETIZATION_ID = mt.MONETIZATION_ID GROUP BY 1
  ), bk AS (SELECT DISTINCT GAME_ID FROM ONTOLOGY_DEMO.GAME_SALES_GEN.BACKUP_GAME_MNTHLY_REVENUE),
  est AS (
    SELECT GAME_ID, ESTIMATED_TOTAL_REVENUE FROM ONTOLOGY_DEMO.GAME_SALES_GEN.ADD_GAME_TMP
    WHERE GAME_ID IS NOT NULL QUALIFY ROW_NUMBER() OVER (PARTITION BY GAME_ID ORDER BY UPDATED_AT DESC NULLS LAST, CREATED_AT DESC NULLS LAST) = 1
  )
  SELECT g.GAME_ID, g.GAME_NAME, g.RELEASE_DATE,
    CASE WHEN ARRAY_CONTAINS('loot_boxes'::VARIANT, t.t) THEN 'SPORTS_PACKS'
         WHEN ARRAY_CONTAINS('battle_pass'::VARIANT, t.t) THEN 'LIVE_BP'
         WHEN ARRAY_CONTAINS('microtransactions'::VARIANT, t.t) THEN 'PREMIUM_MTX'
         WHEN ARRAY_CONTAINS('dlc'::VARIANT, t.t) AND ARRAY_CONTAINS('season_pass'::VARIANT, t.t) THEN 'PREMIUM_DLC_SEASON'
         WHEN ARRAY_CONTAINS('dlc'::VARIANT, t.t) THEN 'PREMIUM_DLC'
         ELSE 'PREMIUM' END AS PROFILE,
    COALESCE(po.LAUNCH_PRICE, CASE WHEN g.RELEASE_DATE < '2006-11-11' THEN 49.99 WHEN g.RELEASE_DATE < '2020-11-12' THEN 59.99 ELSE 69.99 END)::NUMBER(10,2) AS LAUNCH_PRICE,
    IFF(bk.GAME_ID IS NOT NULL, 'BACKUP', 'ESTIMATE') AS TARGET_SOURCE,
    est.ESTIMATED_TOTAL_REVENUE AS ESTIMATED_TOTAL_REVENUE_ACTUAL,
    t.t AS MONETIZATION_TAGS
  FROM ONTOLOGY_DEMO.GAME_SALES.GAMES g
  LEFT JOIN tags t ON t.GAME_ID = g.GAME_ID
  LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PRICE_OVERRIDES po ON po.GAME_ID = g.GAME_ID
  LEFT JOIN bk ON bk.GAME_ID = g.GAME_ID
  LEFT JOIN est ON est.GAME_ID = g.GAME_ID
  WHERE g.RELEASE_DATE IS NOT NULL AND g.RELEASE_DATE <= :as_of;

  -- When each game version went on sale and its relative sales weight
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_AVAILABILITY
  COMMENT = 'Generator input: when each game version went on sale and its relative sales weight. Non-PlayStation versions start at the timed-exclusivity end or a GEN_PLATFORM_DATE_OVERRIDES date. Rebuilt by SP_GEN_CATALOG.'
  AS
  WITH excl AS (
    SELECT GAME_ID, MAX(EXCLUSIVE_END) EXCL_END FROM ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS
    WHERE EXCLUSIVITY_TYPE = 'TIMED_EXPIRED' AND PLATFORM_ID IN (208, 5, 8, 101, 202) GROUP BY 1
  )
  SELECT gp.GAME_ID, gp.PLATFORM_ID,
    COALESCE(ov.AVAILABLE_FROM,
      CASE WHEN gp.PLATFORM_ID = 101 THEN GREATEST(g.RELEASE_DATE, '2020-11-12'::DATE)
           WHEN gp.PLATFORM_ID IN (208, 5, 8, 202) THEN g.RELEASE_DATE
           ELSE GREATEST(g.RELEASE_DATE, COALESCE(excl.EXCL_END, g.RELEASE_DATE)) END) AS AVAILABLE_FROM,
    CASE gp.PLATFORM_ID WHEN 101 THEN 0.55 WHEN 8 THEN 0.45 WHEN 5 THEN 1.0 WHEN 208 THEN 1.0 WHEN 202 THEN 1.0
         WHEN 6 THEN 0.20 WHEN 3 THEN 0.08 WHEN 102 THEN 0.12 WHEN 103 THEN 0.05 WHEN 4 THEN 0.02 ELSE 0.05 END::FLOAT AS WEIGHT,
    gp.PLATFORM_ID IN (208, 5, 8, 101, 202) AS IS_PLAYSTATION
  FROM ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS gp
  JOIN ONTOLOGY_DEMO.GAME_SALES.GAMES g ON g.GAME_ID = gp.GAME_ID
  LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_DATE_OVERRIDES ov ON ov.GAME_ID = gp.GAME_ID AND ov.PLATFORM_ID = gp.PLATFORM_ID
  LEFT JOIN excl ON excl.GAME_ID = gp.GAME_ID;

  -- SKUs per profile; only missing ones are inserted
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS (DIGITAL_PRODUCT_ID, GAME_ID, CATEGORY_ID, PRODUCT_NAME, LIST_PRICE, CURRENCY_CODE, IS_CONSUMABLE, RELEASE_DATE)
  WITH n AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS k FROM TABLE(GENERATOR(ROWCOUNT => 200))),
  gp AS (
    SELECT p.*, p.GAME_NAME AS TITLE,
      IFF(p.TARGET_SOURCE = 'ESTIMATE' AND COALESCE(p.ESTIMATED_TOTAL_REVENUE_ACTUAL, 0) = 0, 0, p.LAUNCH_PRICE) AS BASE_PRICE,
      EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_AVAILABILITY pa WHERE pa.GAME_ID = p.GAME_ID AND pa.IS_PLAYSTATION) AS HAS_PS
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE p
  ), skus AS (
    SELECT GAME_ID, 3 cat, 1 k, TITLE || ' (Digital Edition)' nm, BASE_PRICE price, FALSE cons, RELEASE_DATE rd FROM gp
    UNION ALL
    SELECT GAME_ID, 4, 1, TITLE || ' (Physical Edition)', BASE_PRICE, FALSE, RELEASE_DATE FROM gp
    WHERE BASE_PRICE > 0 AND HAS_PS AND GAME_ID NOT IN (653, 647)   -- digital-only releases
    UNION ALL
    SELECT gp.GAME_ID, 5, n.k + 1, gp.TITLE || ' - DLC Pack ' || (n.k + 1), DECODE(n.k, 0, 14.99, 1, 19.99, 2, 14.99, 29.99),
           FALSE, DATEADD(MONTH, DECODE(n.k, 0, 3, 1, 6, 2, 12, 18), gp.RELEASE_DATE)
    FROM gp JOIN n ON n.k < 4 WHERE gp.PROFILE IN ('PREMIUM_DLC', 'PREMIUM_DLC_SEASON')
    UNION ALL
    SELECT GAME_ID, 7, 1, TITLE || ' - Season Pass', 29.99, FALSE, RELEASE_DATE FROM gp WHERE PROFILE = 'PREMIUM_DLC_SEASON'
    UNION ALL
    -- 4 cosmetic bundles at launch, then one every 2 months
    SELECT gp.GAME_ID, 9, n.k + 1, gp.TITLE || ' - Cosmetic Bundle ' || (n.k + 1), DECODE(MOD(n.k, 4), 0, 4.99, 1, 9.99, 2, 14.99, 19.99),
           FALSE, IFF(n.k < 4, gp.RELEASE_DATE, DATEADD(MONTH, 2 * (n.k - 3), gp.RELEASE_DATE))
    FROM gp JOIN n ON n.k < 12 WHERE gp.PROFILE IN ('PREMIUM_MTX', 'LIVE_BP')
    UNION ALL
    SELECT gp.GAME_ID, 10, n.k + 1, gp.TITLE || DECODE(n.k, 0, ' - Small Boost', ' - Large Boost'), DECODE(n.k, 0, 1.99, 4.99), TRUE, gp.RELEASE_DATE
    FROM gp JOIN n ON n.k < 2 WHERE gp.PROFILE = 'PREMIUM_MTX'
    UNION ALL
    SELECT gp.GAME_ID, 8, n.k + 1, gp.TITLE || ' - Season ' || (n.k + 1) || ' Battle Pass', 9.99, FALSE, DATEADD(MONTH, 3 * n.k, gp.RELEASE_DATE)
    FROM gp JOIN n ON TRUE WHERE gp.PROFILE = 'LIVE_BP'
    UNION ALL
    SELECT gp.GAME_ID, 11, n.k + 1, gp.TITLE || DECODE(n.k, 0, ' - Standard Card Pack', ' - Premium Card Pack Bundle'), DECODE(n.k, 0, 4.99, 9.99), TRUE, gp.RELEASE_DATE
    FROM gp JOIN n ON n.k < 2 WHERE gp.PROFILE = 'SPORTS_PACKS'
    UNION ALL
    SELECT gp.GAME_ID, 12, n.k + 1, gp.TITLE || DECODE(n.k, 0, ' - 10,000 Stubs', 1, ' - 22,500 Stubs', ' - 60,000 Stubs'), DECODE(n.k, 0, 9.99, 1, 19.99, 49.99), TRUE, gp.RELEASE_DATE
    FROM gp JOIN n ON n.k < 3 WHERE gp.PROFILE = 'SPORTS_PACKS'
  ), missing AS (
    SELECT s.* FROM skus s
    WHERE s.rd <= :as_of
      AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS d WHERE d.GAME_ID = s.GAME_ID AND d.PRODUCT_NAME = s.nm)
  )
  SELECT (SELECT COALESCE(MAX(DIGITAL_PRODUCT_ID), 0) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS) + ROW_NUMBER() OVER (ORDER BY GAME_ID, cat, k),
    GAME_ID, cat, nm, price, 'USD', cons, rd
  FROM missing;

  added := SQLROWCOUNT;
  RETURN 'profiles=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE)
    || ' platform_rows=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_AVAILABILITY)
    || ' skus_added=' || :added
    || ' skus_total=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS);
END;
$$;
