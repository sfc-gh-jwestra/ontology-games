CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_DIGITAL_SALES()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Synthetic generator step 3: expands GEN_CATEGORY_TARGETS into unit sales, prices them so every game-month-category matches its target to the cent, and assigns buyers. Base games: one per account per game, buyer must own a compatible console (PS4 version: PS4 or PS5 owner) or be a store-only account for PC/Xbox/Switch/Apple. Non-consumable add-ons: unique per account per SKU and only for base-game owners. Consumables: repeatable, engagement-weighted. Rebuilds DIGITAL_PRODUCT_TRANSACTIONS and the store-only CUSTOMER_ACCOUNTS.'
EXECUTE AS OWNER
AS
$$
DECLARE
  seed NUMBER;
  as_of DATE;
  max_ps_account NUMBER;
  left_base NUMBER;
  left_addon NUMBER;
  passes RESULTSET DEFAULT (SELECT * FROM VALUES (1, '101'), (2, '8'), (3, 'OTHER') AS v(o, ps) ORDER BY o);
  ps VARCHAR;
BEGIN
  SELECT CONFIG_VALUE::NUMBER INTO :seed FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'SEED';
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';

  -- 1. Units: SKU, date and (for base games) platform version
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS AS
  WITH n AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS I FROM TABLE(GENERATOR(ROWCOUNT => 20000))),
  t AS (
    SELECT t.*, g.RELEASE_DATE, LEAST(LAST_DAY(t.REVENUE_MONTH), :as_of) AS WE
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_TARGETS t JOIN ONTOLOGY_DEMO.GAME_SALES.GAMES g ON g.GAME_ID = t.GAME_ID
  ), sk AS (
    SELECT t.GAME_ID, t.REVENUE_MONTH, t.CATEGORY_ID, d.DIGITAL_PRODUCT_ID, d.LIST_PRICE, d.RELEASE_DATE AS SKU_RD, d.IS_CONSUMABLE,
      ROW_NUMBER() OVER (PARTITION BY t.GAME_ID, t.REVENUE_MONTH, t.CATEGORY_ID ORDER BY d.DIGITAL_PRODUCT_ID) AS R,
      COUNT(*) OVER (PARTITION BY t.GAME_ID, t.REVENUE_MONTH, t.CATEGORY_ID) AS M
    FROM t JOIN ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS d
      ON d.GAME_ID = t.GAME_ID AND d.CATEGORY_ID = t.CATEGORY_ID AND d.RELEASE_DATE <= t.WE
     AND (d.CATEGORY_ID <> 8 OR d.RELEASE_DATE > DATEADD(MONTH, -3, LAST_DAY(t.REVENUE_MONTH)))
  ), u0 AS (
    SELECT t.GAME_ID, t.REVENUE_MONTH, t.CATEGORY_ID, t.TARGET_AMOUNT, t.AVG_PRICE, t.RELEASE_DATE, t.WE, n.I,
      ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'sk|' || t.GAME_ID || '|' || t.REVENUE_MONTH || '|' || t.CATEGORY_ID || '|' || n.I) AS US,
      ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'dt|' || t.GAME_ID || '|' || t.REVENUE_MONTH || '|' || t.CATEGORY_ID || '|' || n.I) AS UD,
      ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'tm|' || t.GAME_ID || '|' || t.REVENUE_MONTH || '|' || t.CATEGORY_ID || '|' || n.I) AS UT
    FROM t JOIN n ON n.I < t.UNITS
  ), u1 AS (
    SELECT u0.*, sk.DIGITAL_PRODUCT_ID, sk.IS_CONSUMABLE,
      IFF(u0.CATEGORY_ID IN (3, 4), u0.AVG_PRICE, sk.LIST_PRICE) AS LIST_P,
      -- add-ons need the base game first, so they start the day after the game's release
      GREATEST(u0.REVENUE_MONTH, IFF(u0.CATEGORY_ID IN (3, 4), u0.RELEASE_DATE, DATEADD(DAY, 1, u0.RELEASE_DATE)), sk.SKU_RD) AS WS
    FROM u0 JOIN sk ON sk.GAME_ID = u0.GAME_ID AND sk.REVENUE_MONTH = u0.REVENUE_MONTH AND sk.CATEGORY_ID = u0.CATEGORY_ID
                   AND sk.R = LEAST(sk.M, FLOOR(u0.US * sk.M) + 1)
  ), u2 AS (
    SELECT u1.*,
      CASE WHEN DATE_TRUNC(MONTH, u1.RELEASE_DATE) = u1.REVENUE_MONTH AND u1.UD < 0.4
           THEN DATEADD(DAY, FLOOR(u1.UD / 0.4 * LEAST(7, DATEDIFF(DAY, u1.WS, u1.WE) + 1)), u1.WS)
           ELSE DATEADD(DAY, FLOOR(u1.UD * (DATEDIFF(DAY, u1.WS, u1.WE) + 1)), u1.WS) END AS UNIT_DATE
    FROM u1
  ), ps5_cum AS (
    SELECT SALE_DATE AS D, SUM(COUNT(*)) OVER (ORDER BY SALE_DATE) AS OWNERS
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_SLOTS WHERE GENERATION = 'PS5' GROUP BY SALE_DATE
  ), u2p AS (
    SELECT u2.*, COALESCE(pc.OWNERS, 0) AS PS5_OWNERS
    FROM u2 ASOF JOIN ps5_cum pc MATCH_CONDITION (u2.UNIT_DATE >= pc.D)
  ), pw AS (
    -- a cross-gen game's PS5 version sells in proportion to the PS5 installed base (full weight at 25K scaled owners)
    SELECT u2p.GAME_ID, u2p.REVENUE_MONTH, u2p.CATEGORY_ID, u2p.I, pa.PLATFORM_ID,
      pa.WEIGHT * IFF(pa.PLATFORM_ID = 101 AND ps4.GAME_ID IS NOT NULL, LEAST(1, u2p.PS5_OWNERS / 25000), 1) AS EW
    FROM u2p JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_AVAILABILITY pa
      ON pa.GAME_ID = u2p.GAME_ID AND pa.AVAILABLE_FROM <= u2p.UNIT_DATE AND (u2p.CATEGORY_ID = 3 OR pa.IS_PLAYSTATION)
    LEFT JOIN (SELECT GAME_ID FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PLATFORM_AVAILABILITY WHERE PLATFORM_ID = 8) ps4 ON ps4.GAME_ID = u2p.GAME_ID
    WHERE u2p.CATEGORY_ID IN (3, 4)
  ), plat AS (
    SELECT pw.GAME_ID, pw.REVENUE_MONTH, pw.CATEGORY_ID, pw.I, pw.PLATFORM_ID,
      (SUM(EW) OVER (PARTITION BY GAME_ID, REVENUE_MONTH, CATEGORY_ID, I ORDER BY PLATFORM_ID) - EW)
        / SUM(EW) OVER (PARTITION BY GAME_ID, REVENUE_MONTH, CATEGORY_ID, I) AS LO,
      SUM(EW) OVER (PARTITION BY GAME_ID, REVENUE_MONTH, CATEGORY_ID, I ORDER BY PLATFORM_ID)
        / SUM(EW) OVER (PARTITION BY GAME_ID, REVENUE_MONTH, CATEGORY_ID, I) AS HI,
      ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'pl|' || pw.GAME_ID || '|' || pw.REVENUE_MONTH || '|' || pw.CATEGORY_ID || '|' || pw.I) AS UP
    FROM pw WHERE EW > 0
  ), u3 AS (
    SELECT u2.*, p.PLATFORM_ID,
      DATEADD(MINUTE, FLOOR(u2.UT * 960), DATEADD(HOUR, 8, u2.UNIT_DATE::TIMESTAMP_NTZ)) AS UNIT_TS
    FROM u2 LEFT JOIN plat p ON p.GAME_ID = u2.GAME_ID AND p.REVENUE_MONTH = u2.REVENUE_MONTH AND p.CATEGORY_ID = u2.CATEGORY_ID AND p.I = u2.I
                             AND p.UP >= p.LO AND p.UP < p.HI
  ), priced AS (
    SELECT u3.*,
      ROUND(u3.LIST_P * u3.TARGET_AMOUNT / SUM(u3.LIST_P) OVER (PARTITION BY u3.GAME_ID, u3.REVENUE_MONTH, u3.CATEGORY_ID), 2) AS P0,
      ROW_NUMBER() OVER (PARTITION BY u3.GAME_ID, u3.REVENUE_MONTH, u3.CATEGORY_ID ORDER BY u3.LIST_P DESC, u3.I) AS PR
    FROM u3
  )
  SELECT ROW_NUMBER() OVER (ORDER BY UNIT_TS, GAME_ID, CATEGORY_ID, I) AS UNIT_ID,
    GAME_ID, REVENUE_MONTH, CATEGORY_ID, DIGITAL_PRODUCT_ID, IS_CONSUMABLE, PLATFORM_ID, UNIT_DATE, UNIT_TS, LIST_P,
    (P0 + IFF(PR = 1, TARGET_AMOUNT - SUM(P0) OVER (PARTITION BY GAME_ID, REVENUE_MONTH, CATEGORY_ID), 0))::NUMBER(18,2) AS UNIT_PRICE,
    NULL::NUMBER AS ACCOUNT_ID
  FROM priced;

  -- 2. Store-only accounts (PC / Xbox / Switch / Apple), pool = 1.3 x the largest per-game unit count on that store
  SELECT MAX(ACCOUNT_ID) INTO :max_ps_account FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP;
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS WHERE ACCOUNT_ID > :max_ps_account;
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS (ACCOUNT_ID, PLATFORM_ID, REGION, ACCOUNT_CREATED_DATE, IS_ACTIVE)
  WITH need AS (
    SELECT PLATFORM_ID, CEIL(1.3 * MAX(N)) + 20 AS POOL FROM (
      SELECT PLATFORM_ID, GAME_ID, COUNT(*) N FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS
      WHERE CATEGORY_ID IN (3, 4) AND PLATFORM_ID NOT IN (208, 5, 8, 101, 202) GROUP BY 1, 2) GROUP BY 1
  ), n AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS I FROM TABLE(GENERATOR(ROWCOUNT => 100000)))
  SELECT :max_ps_account + ROW_NUMBER() OVER (ORDER BY need.PLATFORM_ID, n.I), need.PLATFORM_ID,
    CASE WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'srg' || need.PLATFORM_ID || '|' || n.I) < 0.45 THEN 'NA'
         WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'srg' || need.PLATFORM_ID || '|' || n.I) < 0.80 THEN 'EU'
         WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'srg' || need.PLATFORM_ID || '|' || n.I) < 0.90 THEN 'ASIA'
         WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'srg' || need.PLATFORM_ID || '|' || n.I) < 0.95 THEN 'JP' ELSE 'LATAM' END,
    NULL, FALSE
  FROM need JOIN n ON n.I <= need.POOL;

  -- 3. Who can buy which platform version, since when, and how engaged they are (heavy-tailed weight 1..10)
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIGIBILITY AS
  SELECT e.PLATFORM_ID, e.ACCOUNT_ID, MIN(e.OWN_DATE) AS OWN_DATE,
    1 + 9 * POWER(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'eng' || e.ACCOUNT_ID), 3) AS ENG
  FROM (
    SELECT IFF(PLATFORM_ID = 101, 8, PLATFORM_ID) AS PLATFORM_ID, ACCOUNT_ID, SALE_DATE AS OWN_DATE
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP WHERE PLATFORM_ID IN (8, 101)       -- PS4 version: PS4 or PS5 owners
    UNION ALL
    SELECT PLATFORM_ID, ACCOUNT_ID, SALE_DATE FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP WHERE PLATFORM_ID <> 8
    UNION ALL
    SELECT PLATFORM_ID, ACCOUNT_ID, '1990-01-01'::DATE FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS WHERE ACCOUNT_ID > :max_ps_account
  ) e
  GROUP BY 1, 2;

  -- Eligible accounts ranked by ownership date, plus the eligible count at each date (for ASOF lookups)
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIG_RANKED AS
  SELECT e.*, ROW_NUMBER() OVER (PARTITION BY PLATFORM_ID ORDER BY OWN_DATE, ACCOUNT_ID) AS R
  FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIGIBILITY e;
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIG_DAY AS
  SELECT PLATFORM_ID, OWN_DATE, MAX(R) AS C FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIG_RANKED GROUP BY 1, 2;

  -- 4. Base-game buyers: each unit draws 3 random accounts that owned a compatible console (or are store accounts)
  --    on the sale date and don't own the game yet, and keeps the most engaged one; if two units pick the same
  --    account for one game, the earliest keeps it and the rest retry next round.
  --    PS5 versions first, then PS4 (PS5 owners can buy either, but only one copy per game).
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS (
    GAME_ID NUMBER, ACCOUNT_ID NUMBER, UNIT_ID NUMBER, PLATFORM_ID NUMBER, UNIT_TS TIMESTAMP_NTZ, UNIT_DATE DATE);

  FOR p IN passes DO
    ps := p.ps;
    FOR rnd IN 1 TO 12 DO
      -- picks are materialized first so the lookup below is an equality join on (PLATFORM_ID, R)
      CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS AS
      WITH un AS (
        SELECT u.UNIT_ID, u.GAME_ID, IFF(u.PLATFORM_ID = 101, 101, u.PLATFORM_ID) AS PLATFORM_ID, u.UNIT_TS, u.UNIT_DATE
        FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
        WHERE u.CATEGORY_ID IN (3, 4)
          AND (u.PLATFORM_ID::VARCHAR = :ps OR (:ps = 'OTHER' AND u.PLATFORM_ID NOT IN (8, 101)))
          AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS o WHERE o.UNIT_ID = u.UNIT_ID)
      ), uc AS (
        SELECT un.*, ed.C FROM un ASOF JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIG_DAY ed
          MATCH_CONDITION (un.UNIT_DATE >= ed.OWN_DATE) ON ed.PLATFORM_ID = un.PLATFORM_ID
      ), picks AS (
        SELECT uc.*, j.J, (1 + FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'b' || :rnd || '|' || uc.UNIT_ID || '|' || j.J) * uc.C))::NUMBER AS IDX
        FROM uc CROSS JOIN (SELECT 1 AS J UNION ALL SELECT 2 UNION ALL SELECT 3) j WHERE uc.C IS NOT NULL
      )
      SELECT * FROM picks;

      INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS
      WITH best AS (
        SELECT pk.UNIT_ID, pk.GAME_ID, pk.PLATFORM_ID, pk.UNIT_TS, pk.UNIT_DATE, er.ACCOUNT_ID
        FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS pk JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIG_RANKED er ON er.PLATFORM_ID = pk.PLATFORM_ID AND er.R = pk.IDX
        WHERE NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS o WHERE o.GAME_ID = pk.GAME_ID AND o.ACCOUNT_ID = er.ACCOUNT_ID)
        QUALIFY ROW_NUMBER() OVER (PARTITION BY pk.UNIT_ID ORDER BY er.ENG DESC, pk.J) = 1
      )
      SELECT GAME_ID, ACCOUNT_ID, UNIT_ID, PLATFORM_ID, UNIT_TS, UNIT_DATE FROM best
      QUALIFY ROW_NUMBER() OVER (PARTITION BY GAME_ID, ACCOUNT_ID ORDER BY UNIT_TS, UNIT_ID) = 1;
    END FOR;
  END FOR;

  SELECT COUNT(*) INTO :left_base FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
  WHERE u.CATEGORY_ID IN (3, 4) AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS o WHERE o.UNIT_ID = u.UNIT_ID);

  -- 5. Non-consumable add-ons (DLC, season pass, battle pass, cosmetics): base-game owners only, one per account per SKU
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS (
    DIGITAL_PRODUCT_ID NUMBER, ACCOUNT_ID NUMBER, UNIT_ID NUMBER, PLATFORM_ID NUMBER);

  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_RANKED AS
  SELECT o.GAME_ID, o.ACCOUNT_ID, o.UNIT_DATE AS BASE_DATE, o.PLATFORM_ID, e.ENG,
    ROW_NUMBER() OVER (PARTITION BY o.GAME_ID ORDER BY o.UNIT_DATE, o.ACCOUNT_ID) AS R
  FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS o
  JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ELIGIBILITY e ON e.ACCOUNT_ID = o.ACCOUNT_ID AND e.PLATFORM_ID = IFF(o.PLATFORM_ID = 101, 8, o.PLATFORM_ID);
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_DAY AS
  SELECT GAME_ID, BASE_DATE, MAX(R) AS E FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_RANKED GROUP BY 1, 2;

  FOR rnd IN 1 TO 12 DO
    CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS AS
    WITH un AS (
      SELECT u.UNIT_ID, u.GAME_ID, u.DIGITAL_PRODUCT_ID, u.UNIT_TS, u.UNIT_DATE FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
      WHERE u.CATEGORY_ID NOT IN (3, 4) AND NOT u.IS_CONSUMABLE
        AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.UNIT_ID = u.UNIT_ID)
    ), uc AS (
      SELECT un.*, od.E FROM un ASOF JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_DAY od
        MATCH_CONDITION (un.UNIT_DATE > od.BASE_DATE) ON od.GAME_ID = un.GAME_ID
    ), picks AS (
      SELECT uc.*, j.J, (1 + FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'a' || :rnd || '|' || uc.UNIT_ID || '|' || j.J) * uc.E))::NUMBER AS IDX
      FROM uc CROSS JOIN (SELECT 1 AS J UNION ALL SELECT 2 UNION ALL SELECT 3) j WHERE uc.E IS NOT NULL
    )
    SELECT * FROM picks;

    INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS
    WITH best AS (
      SELECT pk.UNIT_ID, pk.DIGITAL_PRODUCT_ID, pk.UNIT_TS, orr.ACCOUNT_ID, orr.PLATFORM_ID
      FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS pk JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_RANKED orr ON orr.GAME_ID = pk.GAME_ID AND orr.R = pk.IDX
      WHERE NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.DIGITAL_PRODUCT_ID = pk.DIGITAL_PRODUCT_ID AND a.ACCOUNT_ID = orr.ACCOUNT_ID)
      QUALIFY ROW_NUMBER() OVER (PARTITION BY pk.UNIT_ID ORDER BY orr.ENG DESC, pk.J) = 1
    )
    SELECT DIGITAL_PRODUCT_ID, ACCOUNT_ID, UNIT_ID, PLATFORM_ID FROM best
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DIGITAL_PRODUCT_ID, ACCOUNT_ID ORDER BY UNIT_TS, UNIT_ID) = 1;
  END FOR;

  -- Leftovers dated before anyone owned the game move to the day after the first base sale (same month only)
  UPDATE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
  SET UNIT_DATE = DATEADD(DAY, 1, f.D),
      UNIT_TS = DATEADD(HOUR, 12, DATEADD(DAY, 1, f.D)::TIMESTAMP_NTZ)
  FROM (SELECT GAME_ID, MIN(UNIT_DATE) AS D FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS GROUP BY 1) f
  WHERE f.GAME_ID = u.GAME_ID AND u.CATEGORY_ID NOT IN (3, 4) AND NOT u.IS_CONSUMABLE
    AND u.UNIT_DATE <= f.D
    AND DATEADD(DAY, 1, f.D) <= LEAST(LAST_DAY(u.REVENUE_MONTH), :as_of)
    AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.UNIT_ID = u.UNIT_ID);

  -- Final exhaustive pass for leftovers: any base-game owner (before the unit date) who lacks the SKU, one per unit
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS
  WITH un AS (
    SELECT u.UNIT_ID, u.GAME_ID, u.DIGITAL_PRODUCT_ID, u.UNIT_DATE,
      ROW_NUMBER() OVER (PARTITION BY u.DIGITAL_PRODUCT_ID ORDER BY u.UNIT_TS, u.UNIT_ID) AS K
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
    WHERE u.CATEGORY_ID NOT IN (3, 4) AND NOT u.IS_CONSUMABLE
      AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.UNIT_ID = u.UNIT_ID)
  ), cand AS (
    SELECT un.UNIT_ID, un.DIGITAL_PRODUCT_ID, un.K, o.ACCOUNT_ID, o.PLATFORM_ID,
      ROW_NUMBER() OVER (PARTITION BY un.UNIT_ID ORDER BY ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'fa' || un.UNIT_ID || '|' || o.ACCOUNT_ID)) AS CR
    FROM un JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_RANKED o ON o.GAME_ID = un.GAME_ID AND o.BASE_DATE < un.UNIT_DATE
    WHERE NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.DIGITAL_PRODUCT_ID = un.DIGITAL_PRODUCT_ID AND a.ACCOUNT_ID = o.ACCOUNT_ID)
  )
  -- unit K of a SKU takes its K-th random candidate, so two leftover units of one SKU can't take the same account
  SELECT DIGITAL_PRODUCT_ID, ACCOUNT_ID, UNIT_ID, PLATFORM_ID FROM cand WHERE CR = K
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DIGITAL_PRODUCT_ID, ACCOUNT_ID ORDER BY UNIT_ID) = 1;

  SELECT COUNT(*) INTO :left_addon FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
  WHERE u.CATEGORY_ID NOT IN (3, 4) AND NOT u.IS_CONSUMABLE
    AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS a WHERE a.UNIT_ID = u.UNIT_ID);

  -- 6. Consumables (boosts, card packs, currency): repeatable; each unit picks the most engaged of 3 random
  --    base-game owners who bought the game before the unit date
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS AS
  WITH cu AS (
    SELECT u.UNIT_ID, u.GAME_ID, u.UNIT_DATE, od.E FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
    ASOF JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_DAY od MATCH_CONDITION (u.UNIT_DATE > od.BASE_DATE) ON u.GAME_ID = od.GAME_ID
    WHERE u.IS_CONSUMABLE
  )
  SELECT cu.UNIT_ID, j.J, cu.GAME_ID,
    (1 + FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cp' || cu.UNIT_ID || '|' || j.J) * COALESCE(cu.E, 1)))::NUMBER AS IDX
  FROM cu CROSS JOIN (SELECT 1 AS J UNION ALL SELECT 2 UNION ALL SELECT 3) j;

  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSUMABLE_BUYERS AS
  SELECT p.UNIT_ID, ow.ACCOUNT_ID, ow.PLATFORM_ID, ow.BASE_DATE
  FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_PICKS p JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_OWNER_RANKED ow ON ow.GAME_ID = p.GAME_ID AND ow.R = p.IDX
  QUALIFY ROW_NUMBER() OVER (PARTITION BY p.UNIT_ID ORDER BY ow.ENG DESC, p.J) = 1;

  -- 7. Transactions (commission: PlayStation store and physical 0%, other stores 30%)
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS;
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS
    (TRANSACTION_ID, DIGITAL_PRODUCT_ID, GAME_ID, ACCOUNT_ID, TRANSACTION_TIMESTAMP, QUANTITY, UNIT_PRICE, GROSS_REVENUE, PLATFORM_COMMISSION_PCT, NET_DEVELOPER_REVENUE, PLATFORM_ID)
  WITH a AS (
    SELECT u.*, COALESCE(b.ACCOUNT_ID, ad.ACCOUNT_ID, cb.ACCOUNT_ID) AS BUYER,
      COALESCE(b.PLATFORM_ID, ad.PLATFORM_ID, cb.PLATFORM_ID) AS PLAT,
      -- a consumable whose only possible buyer bought the game later is moved to just after that base purchase
      IFF(cb.BASE_DATE >= u.UNIT_DATE, DATEADD(HOUR, 1, bo.UNIT_TS), u.UNIT_TS) AS TS
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u
    LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS b ON b.UNIT_ID = u.UNIT_ID
    LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_ADDON_OWNERS ad ON ad.UNIT_ID = u.UNIT_ID
    LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSUMABLE_BUYERS cb ON cb.UNIT_ID = u.UNIT_ID
    LEFT JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_BASE_OWNERS bo ON bo.GAME_ID = u.GAME_ID AND bo.ACCOUNT_ID = cb.ACCOUNT_ID
  )
  SELECT ROW_NUMBER() OVER (ORDER BY TS, UNIT_ID), DIGITAL_PRODUCT_ID, GAME_ID, BUYER, TS, 1, UNIT_PRICE, UNIT_PRICE,
    IFF(PLAT IN (208, 5, 8, 101, 202), 0, 0.30),
    ROUND(UNIT_PRICE * (1 - IFF(PLAT IN (208, 5, 8, 101, 202), 0, 0.30)), 2),
    PLAT
  FROM a WHERE BUYER IS NOT NULL;

  -- 8. Store-only accounts: created on first purchase; drop unused ones
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS c
  WHERE c.ACCOUNT_ID > :max_ps_account
    AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS t WHERE t.ACCOUNT_ID = c.ACCOUNT_ID);
  UPDATE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS c
  SET ACCOUNT_CREATED_DATE = f.D
  FROM (SELECT ACCOUNT_ID, MIN(TRANSACTION_TIMESTAMP)::DATE AS D FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS
        WHERE ACCOUNT_ID > :max_ps_account GROUP BY 1) f
  WHERE c.ACCOUNT_ID = f.ACCOUNT_ID;

  RETURN 'units=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS)
    || ' transactions=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS)
    || ' gross=' || (SELECT SUM(GROSS_REVENUE)::NUMBER(18,2) FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS)
    || ' unassigned_base=' || :left_base || ' unassigned_addon=' || :left_addon
    || ' unassigned_consumable=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_UNITS u WHERE u.IS_CONSUMABLE
                                      AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSUMABLE_BUYERS c WHERE c.UNIT_ID = u.UNIT_ID))
    || ' store_accounts=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS WHERE ACCOUNT_ID > :max_ps_account);
END;
$$;
