CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_SUBSCRIPTIONS()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Synthetic generator step 4: annual PlayStation Plus charges. Subscribers per year = PS_PLUS_SUBSCRIBER_HISTORY / REVENUE_SCALE_DIVISOR. Each subscriber is charged once a year on the anniversary of their first charge; ~80% renew, churned accounts never return (so billing periods never overlap). Subscribers must own a PS3/PS4/PS5 by their first charge. Legacy PS Plus until 2022-06-13 ($49.99, $59.99 from 2017-09-05), then Essential/Extra/Premium (60/25/15%) with the 2023-09-06 price increase. Rebuilds SUBSCRIPTION_CHARGES.'
EXECUTE AS OWNER
AS
$$
DECLARE
  seed NUMBER;
  divisor NUMBER;
  as_of DATE;
  target NUMBER;
  prev_active NUMBER;
  keep NUMBER;
BEGIN
  SELECT CONFIG_VALUE::NUMBER INTO :seed FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'SEED';
  SELECT CONFIG_VALUE::NUMBER INTO :divisor FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'REVENUE_SCALE_DIVISOR';
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';

  -- First date each account owned a PS Plus capable console (PS3, PS4, PS5)
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUB_ELIGIBLE AS
  SELECT ACCOUNT_ID, MIN(SALE_DATE) AS OWN_DATE FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP
  WHERE PLATFORM_ID IN (5, 8, 101) GROUP BY 1;

  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS (
    ACCOUNT_ID NUMBER, FIRST_CHARGE DATE, START_YEAR NUMBER, LAST_YEAR NUMBER);

  FOR y IN 2010 TO 2026 DO
    SELECT ROUND(SUBSCRIBERS_ACTUAL / :divisor) INTO :target FROM ONTOLOGY_DEMO.GAME_SALES_GEN.PS_PLUS_SUBSCRIBER_HISTORY WHERE SUB_YEAR = :y;
    SELECT COUNT(*) INTO :prev_active FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS WHERE LAST_YEAR = :y - 1;
    keep := LEAST(:target, FLOOR(0.8 * :prev_active));

    -- renewals: a random 80% of last year's subscribers (fewer if the subscriber base shrank)
    UPDATE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS s SET LAST_YEAR = :y
    FROM (SELECT ACCOUNT_ID FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS WHERE LAST_YEAR = :y - 1
          QUALIFY ROW_NUMBER() OVER (ORDER BY ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'renew' || :y || '|' || ACCOUNT_ID)) <= :keep) r
    WHERE s.ACCOUNT_ID = r.ACCOUNT_ID;

    -- new subscribers: never subscribed before, owned a capable console before their first charge
    INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS
    WITH win AS (
      SELECT GREATEST(DATE_FROM_PARTS(:y, 1, 1), '2010-06-29'::DATE) AS WS, LEAST(DATE_FROM_PARTS(:y, 12, 31), :as_of) AS WE
    ), cand AS (
      SELECT e.ACCOUNT_ID, GREATEST(e.OWN_DATE, win.WS) AS S, win.WE
      FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUB_ELIGIBLE e CROSS JOIN win
      WHERE e.OWN_DATE <= win.WE
        AND NOT EXISTS (SELECT 1 FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS s WHERE s.ACCOUNT_ID = e.ACCOUNT_ID)
      QUALIFY ROW_NUMBER() OVER (ORDER BY ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'new' || :y || '|' || e.ACCOUNT_ID)) <= :target - :keep
    )
    SELECT ACCOUNT_ID,
      DATEADD(DAY, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'fc' || ACCOUNT_ID) * (DATEDIFF(DAY, S, WE) + 1)), S), :y, :y
    FROM cand;
  END FOR;

  -- One charge per subscriber per active year on the anniversary of the first charge (none after the as-of date)
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES;
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES (CHARGE_ID, PLAN_ID, ACCOUNT_ID, CHARGE_TIMESTAMP, BILLING_PERIOD_START, BILLING_PERIOD_END, GROSS_REVENUE)
  WITH yrs AS (SELECT 2009 + ROW_NUMBER() OVER (ORDER BY SEQ4()) AS Y FROM TABLE(GENERATOR(ROWCOUNT => 17))),
  ch AS (
    SELECT s.ACCOUNT_ID, DATEADD(YEAR, yrs.Y - s.START_YEAR, s.FIRST_CHARGE) AS D,
      ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'tier' || s.ACCOUNT_ID) AS UT
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS s JOIN yrs ON yrs.Y BETWEEN s.START_YEAR AND s.LAST_YEAR
  ), priced AS (
    SELECT ch.*,
      CASE WHEN D < '2022-06-13' THEN 1 WHEN UT < 0.60 THEN 2 WHEN UT < 0.85 THEN 3 ELSE 4 END AS PLAN_ID
    FROM ch WHERE D <= :as_of
  )
  SELECT ROW_NUMBER() OVER (ORDER BY D, ACCOUNT_ID), PLAN_ID, ACCOUNT_ID,
    DATEADD(MINUTE, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'ct' || ACCOUNT_ID || '|' || D) * 1440), D::TIMESTAMP_NTZ),
    D, DATEADD(DAY, -1, DATEADD(YEAR, 1, D)),
    CASE PLAN_ID
      WHEN 1 THEN IFF(D < '2017-09-05', 49.99, 59.99)
      WHEN 2 THEN IFF(D < '2023-09-06', 59.99, 79.99)
      WHEN 3 THEN IFF(D < '2023-09-06', 99.99, 134.99)
      ELSE IFF(D < '2023-09-06', 119.99, 159.99) END
  FROM priced;

  RETURN 'subscribers=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_SUBSCRIBERS)
    || ' charges=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES)
    || ' gross=' || (SELECT SUM(GROSS_REVENUE)::NUMBER(18,2) FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES);
END;
$$;
