CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GENERATE_SALES()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Rebuilds all synthetic GAME_SALES data deterministically (SEED in SALES_GEN_CONFIG). Source figures (BACKUP_GAME_MNTHLY_REVENUE, ADD_GAME_TMP.ESTIMATED_TOTAL_REVENUE, console and PS Plus history) are actual real-world values; every figure is divided by REVENUE_SCALE_DIVISOR (1000). Run after adding games (add-game-data-ontology skill Phase 6).'
EXECUTE AS OWNER
AS
$$
DECLARE
  r0 VARCHAR; r1 VARCHAR; r2 VARCHAR; r3 VARCHAR; r4 VARCHAR;
  as_of DATE;
BEGIN
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';
  CALL ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_CATALOG() INTO :r0;
  CALL ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_CUSTOMERS_AND_HARDWARE() INTO :r1;
  CALL ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_REVENUE_TARGETS() INTO :r2;
  CALL ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_DIGITAL_SALES() INTO :r3;
  CALL ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_SUBSCRIPTIONS() INTO :r4;

  -- Active = any hardware, digital purchase or subscription charge in the 24 months before the as-of date
  UPDATE ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS c
  SET IS_ACTIVE = (a.ACCOUNT_ID IS NOT NULL)
  FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS c2
  LEFT JOIN (
    SELECT ACCOUNT_ID FROM ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS WHERE SALE_TIMESTAMP >= DATEADD(MONTH, -24, :as_of)
    UNION SELECT ACCOUNT_ID FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS WHERE TRANSACTION_TIMESTAMP >= DATEADD(MONTH, -24, :as_of)
    UNION SELECT ACCOUNT_ID FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES WHERE CHARGE_TIMESTAMP >= DATEADD(MONTH, -24, :as_of)) a
    ON a.ACCOUNT_ID = c2.ACCOUNT_ID
  WHERE c.ACCOUNT_ID = c2.ACCOUNT_ID;

  RETURN 'catalog: ' || :r0 || ' | hardware: ' || :r1 || ' | targets: ' || :r2 || ' | digital: ' || :r3 || ' | subscriptions: ' || :r4;
END;
$$;
