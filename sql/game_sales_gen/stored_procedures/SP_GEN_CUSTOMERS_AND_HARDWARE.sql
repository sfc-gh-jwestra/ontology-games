CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_CUSTOMERS_AND_HARDWARE()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Synthetic generator step 1: PlayStation customers and hardware sales. Console units per year = CONSOLE_SHIPMENT_HISTORY / REVENUE_SCALE_DIVISOR. One console per generation per account; ~60% of a generation''s buyers upgrade from the previous generation (owned >= 12 months). Rebuilds CUSTOMER_ACCOUNTS (PlayStation accounts) and HARDWARE_SALES_TRANSACTIONS.'
EXECUTE AS OWNER
AS
$$
DECLARE
  seed NUMBER;
  divisor NUMBER;
  as_of DATE;
  gens RESULTSET DEFAULT (SELECT * FROM VALUES ('PS2', NULL, 1), ('PS3', 'PS2', 2), ('PS_VITA', 'PS3', 3), ('PS4', 'PS3', 4), ('PS5', 'PS4', 5) AS v(g, p, o) ORDER BY o);
  g VARCHAR;
  p VARCHAR;
BEGIN
  SELECT CONFIG_VALUE::NUMBER INTO :seed FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'SEED';
  SELECT CONFIG_VALUE::NUMBER INTO :divisor FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'REVENUE_SCALE_DIVISOR';
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';

  -- 1. One row per scaled console unit, dated with holiday-weighted monthly seasonality
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_SLOTS AS
  WITH launch AS (
    SELECT * FROM VALUES ('PS2','2000-03-04'::DATE),('PS3','2006-11-11'::DATE),('PS_VITA','2011-12-17'::DATE),('PS4','2013-11-15'::DATE),('PS5','2020-11-12'::DATE) AS v(GENERATION, LAUNCH_DATE)
  ), mw AS (
    SELECT * FROM VALUES (1,.06),(2,.055),(3,.06),(4,.055),(5,.055),(6,.065),(7,.06),(8,.065),(9,.075),(10,.08),(11,.17),(12,.2) AS v(MON, W)
  ), gy AS (
    SELECT h.GENERATION, h.PLATFORM_ID, h.SALES_YEAR, l.LAUNCH_DATE, ROUND(h.UNITS_ACTUAL / :divisor) AS UNITS
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.CONSOLE_SHIPMENT_HISTORY h JOIN launch l ON l.GENERATION = h.GENERATION
  ), months AS (
    SELECT gy.*, mw.MON, mw.W,
      GREATEST(DATE_FROM_PARTS(gy.SALES_YEAR, mw.MON, 1), gy.LAUNCH_DATE) AS WIN_START,
      LEAST(LAST_DAY(DATE_FROM_PARTS(gy.SALES_YEAR, mw.MON, 1)), :as_of) AS WIN_END
    FROM gy JOIN mw ON TRUE
    WHERE LAST_DAY(DATE_FROM_PARTS(gy.SALES_YEAR, mw.MON, 1)) >= gy.LAUNCH_DATE
      AND DATE_FROM_PARTS(gy.SALES_YEAR, mw.MON, 1) <= :as_of
  ), cum AS (
    SELECT months.*,
      (SUM(W) OVER (PARTITION BY GENERATION, SALES_YEAR ORDER BY MON) - W) / SUM(W) OVER (PARTITION BY GENERATION, SALES_YEAR) AS LO,
      SUM(W) OVER (PARTITION BY GENERATION, SALES_YEAR ORDER BY MON) / SUM(W) OVER (PARTITION BY GENERATION, SALES_YEAR) AS HI
    FROM months
  ), n AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS I FROM TABLE(GENERATOR(ROWCOUNT => 30000))),
  units AS (
    SELECT gy.GENERATION, gy.PLATFORM_ID, gy.SALES_YEAR, n.I,
      (n.I + ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cf' || gy.GENERATION || gy.SALES_YEAR || n.I)) / gy.UNITS AS F
    FROM gy JOIN n ON n.I < gy.UNITS
  )
  SELECT ROW_NUMBER() OVER (ORDER BY SALE_DATE, GENERATION, I) AS SLOT_ID, GENERATION, PLATFORM_ID, SALE_DATE
  FROM (
    SELECT u.GENERATION, u.PLATFORM_ID, u.I,
      DATEADD(DAY, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cd' || u.GENERATION || u.SALES_YEAR || u.I) * (DATEDIFF(DAY, c.WIN_START, c.WIN_END) + 1)), c.WIN_START) AS SALE_DATE
    FROM units u JOIN cum c ON c.GENERATION = u.GENERATION AND c.SALES_YEAR = u.SALES_YEAR AND u.F >= c.LO AND u.F < c.HI
  );

  -- 2. Assign slots to accounts generation by generation (one console per generation per account).
  --    ~60% of slots go to random previous-generation owners whose console is >= 365 days older;
  --    pairs that would violate the gap fall back to a new account.
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP (
    ACCOUNT_ID NUMBER, GENERATION VARCHAR, PLATFORM_ID NUMBER, SLOT_ID NUMBER, SALE_DATE DATE, IS_UPGRADE BOOLEAN);

  FOR r IN gens DO
    g := r.g;
    p := r.p;
    INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP
    WITH s AS (SELECT * FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_SLOTS WHERE GENERATION = :g),
    up_slots AS (
      SELECT SLOT_ID, SALE_DATE, ROW_NUMBER() OVER (ORDER BY SALE_DATE, SLOT_ID) AS R
      FROM s WHERE ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'up' || SLOT_ID) < 0.6 AND :p IS NOT NULL),
    pool AS (
      SELECT ACCOUNT_ID, DATEADD(DAY, 365, SALE_DATE) AS READY
      FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP WHERE GENERATION = :p
      QUALIFY ROW_NUMBER() OVER (ORDER BY ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'pool' || :g || ACCOUNT_ID)) <= (SELECT COUNT(*) FROM up_slots)),
    pool_r AS (SELECT ACCOUNT_ID, READY, ROW_NUMBER() OVER (ORDER BY READY, ACCOUNT_ID) AS R FROM pool),
    paired AS (SELECT u.SLOT_ID, pr.ACCOUNT_ID FROM up_slots u JOIN pool_r pr ON u.R = pr.R WHERE u.SALE_DATE >= pr.READY),
    mx AS (SELECT COALESCE(MAX(ACCOUNT_ID), 0) AS M FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP)
    SELECT COALESCE(pr.ACCOUNT_ID, mx.M + ROW_NUMBER() OVER (PARTITION BY pr.ACCOUNT_ID IS NULL ORDER BY s.SALE_DATE, s.SLOT_ID)),
           s.GENERATION, s.PLATFORM_ID, s.SLOT_ID, s.SALE_DATE, pr.ACCOUNT_ID IS NOT NULL
    FROM s LEFT JOIN paired pr ON pr.SLOT_ID = s.SLOT_ID CROSS JOIN mx;
  END FOR;

  -- 3. PlayStation customer accounts (home platform = first console)
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS;
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS (ACCOUNT_ID, PLATFORM_ID, REGION, ACCOUNT_CREATED_DATE, IS_ACTIVE)
  SELECT ACCOUNT_ID, PLATFORM_ID,
    CASE WHEN u < 0.40 THEN 'NA' WHEN u < 0.75 THEN 'EU' WHEN u < 0.85 THEN 'JP' WHEN u < 0.95 THEN 'ASIA' ELSE 'LATAM' END,
    SALE_DATE, FALSE
  FROM (SELECT ACCOUNT_ID, PLATFORM_ID, SALE_DATE, ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'rg' || ACCOUNT_ID) AS u
        FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP
        QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_ID ORDER BY SALE_DATE, SLOT_ID) = 1);

  -- 4. Hardware sales: consoles (model by date), extra controllers (0/1/2 at 60/30/10%),
  --    PS VR (5,000 PS4 owners) and PS VR2 (2,000 PS5 owners), dated after console and headset release
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS;
  INSERT INTO ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS (TRANSACTION_ID, HARDWARE_PRODUCT_ID, ACCOUNT_ID, SALE_TIMESTAMP, REGION, QUANTITY, UNIT_PRICE, GROSS_REVENUE)
  WITH own AS (
    SELECT o.*, ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'md' || o.SLOT_ID) AS U FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP o
  ), consoles AS (
    SELECT ACCOUNT_ID, SALE_DATE AS D, SLOT_ID AS K,
      CASE GENERATION
        WHEN 'PS2' THEN IFF(SALE_DATE < '2004-11-01', 1, 2)
        WHEN 'PS3' THEN CASE WHEN SALE_DATE < '2009-09-01' THEN 3 WHEN SALE_DATE < '2012-09-25' THEN 4 ELSE 5 END
        WHEN 'PS_VITA' THEN 6
        WHEN 'PS4' THEN CASE WHEN SALE_DATE < '2016-09-15' THEN 7 WHEN SALE_DATE < '2016-11-10' THEN 8 WHEN U < 0.75 THEN 8 ELSE 9 END
        WHEN 'PS5' THEN CASE WHEN SALE_DATE < '2023-11-10' THEN IFF(U < 0.7, 10, 11) WHEN SALE_DATE < '2024-11-07' THEN 12 WHEN U < 0.75 THEN 12 ELSE 13 END
      END AS HW
    FROM own
  ), ctl_n AS (
    SELECT o.*, CASE WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cn' || SLOT_ID) < 0.6 THEN 0
                     WHEN ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cn' || SLOT_ID) < 0.9 THEN 1 ELSE 2 END AS C
    FROM own o WHERE GENERATION <> 'PS_VITA'
  ), controllers AS (
    SELECT c.ACCOUNT_ID, x.D, c.SLOT_ID * 10 + x.J AS K,
      CASE c.GENERATION WHEN 'PS2' THEN 14 WHEN 'PS3' THEN 15 WHEN 'PS4' THEN 16
        ELSE IFF(x.D >= '2023-01-26' AND ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'edge' || c.SLOT_ID || x.J) < 0.1, 18, 17) END AS HW
    FROM ctl_n c,
    LATERAL (SELECT j.J, LEAST(:as_of, GREATEST(DATEADD(DAY, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'cdt' || c.SLOT_ID || j.J) * 365), c.SALE_DATE),
                                                     IFF(c.GENERATION = 'PS3', '2007-11-11'::DATE, c.SALE_DATE))) AS D
             FROM (SELECT 1 AS J UNION ALL SELECT 2) j WHERE j.J <= c.C) x
  ), vr_spec AS (
    SELECT HW, GENERATION, START_D, COALESCE(END_D, :as_of) AS END_D, UNITS
    FROM VALUES (19, 'PS4', '2016-10-13'::DATE, '2020-12-31'::DATE, 5000), (20, 'PS5', '2023-02-22'::DATE, NULL::DATE, 2000) AS t(HW, GENERATION, START_D, END_D, UNITS)
  ), vr AS (
    SELECT o.ACCOUNT_ID, v.HW, v.HW * 1000000 + o.SLOT_ID AS K,
      DATEADD(DAY, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'vrd' || v.HW || o.ACCOUNT_ID)
                         * (DATEDIFF(DAY, GREATEST(o.SALE_DATE, v.START_D), v.END_D) + 1)), GREATEST(o.SALE_DATE, v.START_D)) AS D
    FROM vr_spec v JOIN own o ON o.GENERATION = v.GENERATION AND o.SALE_DATE <= v.END_D
    QUALIFY ROW_NUMBER() OVER (PARTITION BY v.HW ORDER BY ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'vrp' || v.HW || o.ACCOUNT_ID)) <= v.UNITS
  ), allhw AS (
    SELECT ACCOUNT_ID, D, K, HW, 'C' AS T FROM consoles
    UNION ALL SELECT ACCOUNT_ID, D, K, HW, 'A' FROM controllers
    UNION ALL SELECT ACCOUNT_ID, D, K, HW, 'V' FROM vr
  )
  SELECT ROW_NUMBER() OVER (ORDER BY a.D, a.T, a.K),
    a.HW, a.ACCOUNT_ID,
    DATEADD(MINUTE, FLOOR(ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'hm' || a.T || a.K) * 780), DATEADD(HOUR, 10, a.D::TIMESTAMP_NTZ)),
    ca.REGION, 1, hp.LIST_PRICE, hp.LIST_PRICE
  FROM allhw a
  JOIN ONTOLOGY_DEMO.GAME_SALES.HARDWARE_PRODUCTS hp ON hp.HARDWARE_PRODUCT_ID = a.HW
  JOIN ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS ca ON ca.ACCOUNT_ID = a.ACCOUNT_ID;

  RETURN 'slots=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_SLOTS)
    || ' accounts=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS)
    || ' upgrades=' || (SELECT COUNT_IF(IS_UPGRADE) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CONSOLE_OWNERSHIP)
    || ' hardware_rows=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS);
END;
$$;
