CREATE OR REPLACE PROCEDURE ONTOLOGY_DEMO.GAME_SALES_GEN.SP_GEN_REVENUE_TARGETS()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Synthetic generator step 2: builds GAME_REVENUE_TARGETS (game-month, 1/1000 scale) and GEN_CATEGORY_TARGETS (game-month-category units). BACKUP games use BACKUP_GAME_MNTHLY_REVENUE / divisor; other games spread ADD_GAME_TMP actual estimate / divisor over the SP_GENERATE_MONTHLY_REVENUE lifecycle curve (ported to SQL, hash noise instead of random.seed).'
EXECUTE AS OWNER
AS
$$
DECLARE
  seed NUMBER;
  divisor NUMBER;
  as_of DATE;
BEGIN
  SELECT CONFIG_VALUE::NUMBER INTO :seed FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'SEED';
  SELECT CONFIG_VALUE::NUMBER INTO :divisor FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'REVENUE_SCALE_DIVISOR';
  SELECT CONFIG_VALUE::DATE INTO :as_of FROM ONTOLOGY_DEMO.GAME_SALES_GEN.SALES_GEN_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE';

  -- 1. Game-month targets
  DELETE FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS;

  INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS (GAME_ID, REVENUE_MONTH, MONTH_INDEX, LIFECYCLE_TAG, TARGET_AMOUNT, TARGET_SOURCE)
  SELECT b.GAME_ID, b.REVENUE_MONTH, DATEDIFF(MONTH, DATE_TRUNC(MONTH, g.RELEASE_DATE), b.REVENUE_MONTH), b.REVENUE_SOURCE,
         ROUND(b.MONTHLY_INCOME / :divisor, 2), 'BACKUP'
  FROM ONTOLOGY_DEMO.GAME_SALES_GEN.BACKUP_GAME_MNTHLY_REVENUE b
  JOIN ONTOLOGY_DEMO.GAME_SALES.GAMES g ON g.GAME_ID = b.GAME_ID;

  INSERT INTO ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS (GAME_ID, REVENUE_MONTH, MONTH_INDEX, LIFECYCLE_TAG, TARGET_AMOUNT, TARGET_SOURCE)
  WITH n AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS M FROM TABLE(GENERATOR(ROWCOUNT => 72))),
  gm AS (
    SELECT p.GAME_ID, p.PROFILE, DATE_TRUNC(MONTH, p.RELEASE_DATE) AS RM, ROUND(p.ESTIMATED_TOTAL_REVENUE_ACTUAL / :divisor, 2) AS TOTAL,
      CASE WHEN ARRAY_CONTAINS('free_to_play'::VARIANT, t) AND (ARRAY_CONTAINS('microtransactions'::VARIANT, t) OR ARRAY_CONTAINS('battle_pass'::VARIANT, t)) THEN 'f2p_live_service'
           WHEN ARRAY_CONTAINS('free_to_play'::VARIANT, t) THEN 'f2p_only'
           WHEN ARRAY_CONTAINS('microtransactions'::VARIANT, t) AND NOT ARRAY_CONTAINS('dlc'::VARIANT, t) THEN 'premium_mtx'
           WHEN (ARRAY_CONTAINS('dlc'::VARIANT, t) OR ARRAY_CONTAINS('loot_boxes'::VARIANT, t)) AND ARRAY_CONTAINS('season_pass'::VARIANT, t) THEN 'premium_dlc_season'
           WHEN ARRAY_CONTAINS('dlc'::VARIANT, t) OR ARRAY_CONTAINS('loot_boxes'::VARIANT, t) THEN 'premium_dlc'
           ELSE 'premium_only' END AS MODEL
    FROM (SELECT gp.*, COALESCE(gp.MONETIZATION_TAGS, ARRAY_CONSTRUCT()) AS t FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE gp) p
    WHERE p.TARGET_SOURCE = 'ESTIMATE' AND p.ESTIMATED_TOTAL_REVENUE_ACTUAL > 0
  ),
  w AS (
    SELECT gm.GAME_ID, gm.PROFILE, gm.MODEL, gm.TOTAL, n.M, DATEADD(MONTH, n.M, gm.RM) AS MD,
      (CASE gm.MODEL
         WHEN 'premium_only' THEN CASE WHEN n.M = 0 THEN 40 WHEN n.M = 1 THEN 15 WHEN n.M = 2 THEN 10 WHEN n.M <= 5 THEN 5 WHEN n.M <= 11 THEN 2 ELSE GREATEST(0.1, 2.0 * EXP(-0.15 * (n.M - 11))) END
         WHEN 'premium_dlc' THEN CASE WHEN n.M = 0 THEN 30 WHEN n.M = 1 THEN 12 WHEN n.M = 2 THEN 8 WHEN n.M <= 5 THEN 4 WHEN n.M <= 11 THEN 1.5 ELSE GREATEST(0.05, 1.5 * EXP(-0.12 * (n.M - 11))) END
                                 + DECODE(n.M, 3, 5, 6, 4, 12, 3, 0)
         WHEN 'premium_dlc_season' THEN CASE WHEN n.M = 0 THEN 25 WHEN n.M = 1 THEN 10 WHEN n.M = 2 THEN 7 WHEN n.M <= 5 THEN 3.5 WHEN n.M <= 11 THEN 1.5 ELSE GREATEST(0.05, 1.0 * EXP(-0.1 * (n.M - 11))) END
                                 + DECODE(n.M, 6, 6, 12, 5, 18, 4, 0)
         WHEN 'premium_mtx' THEN CASE WHEN n.M = 0 THEN 20 WHEN n.M = 1 THEN 8 WHEN n.M = 2 THEN 5 WHEN n.M <= 11 THEN 3 WHEN n.M <= 23 THEN 2.5 ELSE GREATEST(0.1, 2.0 * EXP(-0.1 * (n.M - 23))) END
         WHEN 'f2p_live_service' THEN CASE WHEN n.M = 0 THEN 2 WHEN n.M = 1 THEN 5 WHEN n.M = 2 THEN 8 WHEN n.M <= 5 THEN 10 WHEN n.M <= 11 THEN 8 WHEN n.M <= 23 THEN 6 WHEN n.M <= 35 THEN 4 ELSE GREATEST(0.2, 3.0 * EXP(-0.08 * (n.M - 35))) END
                                 + IFF(n.M > 2 AND MOD(n.M, 3) = 0, 2, 0)
         WHEN 'f2p_only' THEN CASE WHEN n.M = 0 THEN 3 WHEN n.M <= 2 THEN 8 WHEN n.M <= 5 THEN 6 WHEN n.M <= 11 THEN 3 ELSE GREATEST(0.1, 2.0 * EXP(-0.15 * (n.M - 11))) END
       END)
      * (1.0 + (ONTOLOGY_DEMO.GAME_SALES_GEN.UDF_U01(:seed, 'curve' || gm.GAME_ID || '_' || n.M) * 0.2 - 0.1))
      * IFF(MONTH(DATEADD(MONTH, n.M, gm.RM)) IN (11, 12) AND n.M > 0, 1.3, 1.0) AS W,
      CASE WHEN n.M = 0 THEN 'launch'
           WHEN gm.MODEL IN ('premium_dlc', 'premium_dlc_season') AND n.M IN (3, 6, 12, 18) THEN 'dlc_bump'
           WHEN (gm.MODEL = 'f2p_live_service' OR gm.PROFILE = 'LIVE_BP') AND n.M > 2 AND MOD(n.M, 3) = 0 THEN 'seasonal'
           WHEN n.M <= 6 THEN 'ongoing' ELSE 'tail' END AS TAG
    FROM gm JOIN n ON n.M < DECODE(gm.MODEL, 'premium_only', 36, 'f2p_only', 36, 'f2p_live_service', 72, 48)
    WHERE DATEADD(MONTH, n.M, gm.RM) <= DATE_TRUNC(MONTH, :as_of::DATE)
  ),
  amt AS (
    SELECT w.*, ROUND(TOTAL * W / SUM(W) OVER (PARTITION BY GAME_ID), 2) AS A,
      ROW_NUMBER() OVER (PARTITION BY GAME_ID ORDER BY W DESC, M) AS WR
    FROM w
  )
  SELECT GAME_ID, MD, M, TAG,
    A + IFF(WR = 1, TOTAL - SUM(A) OVER (PARTITION BY GAME_ID), 0), 'ESTIMATE'
  FROM amt;

  -- 2. Split each game-month into revenue categories (profile x lifecycle weights; BASE_GAME by digital share
  --    by year; categories with no SKU released yet fold into BASE_GAME_DIGITAL), keeping each month exact.
  CREATE OR REPLACE TRANSIENT TABLE ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_TARGETS AS
  WITH t AS (
    SELECT t.*, p.PROFILE, p.LAUNCH_PRICE, LAST_DAY(t.REVENUE_MONTH) AS ME,
      CASE WHEN YEAR(t.REVENUE_MONTH) <= 2012 THEN 0.05 WHEN YEAR(t.REVENUE_MONTH) <= 2016 THEN 0.25 WHEN YEAR(t.REVENUE_MONTH) <= 2019 THEN 0.45
           WHEN YEAR(t.REVENUE_MONTH) <= 2022 THEN 0.65 ELSE 0.75 END AS DIGITAL_SHARE
    FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS t JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE p ON p.GAME_ID = t.GAME_ID
  ), sku_av AS (
    -- SKUs on sale by month end; battle pass only the current season
    SELECT t.GAME_ID, t.REVENUE_MONTH, d.CATEGORY_ID, AVG(d.LIST_PRICE) AS AVG_PRICE
    FROM t JOIN ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS d ON d.GAME_ID = t.GAME_ID AND d.RELEASE_DATE <= t.ME
    WHERE d.CATEGORY_ID NOT IN (3, 4, 8) OR (d.CATEGORY_ID = 8 AND d.RELEASE_DATE > DATEADD(MONTH, -3, t.ME))
    GROUP BY 1, 2, 3
  ), has_phys AS (SELECT DISTINCT GAME_ID FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS WHERE CATEGORY_ID = 4),
  split_raw AS (
    SELECT t.GAME_ID, t.REVENUE_MONTH, t.MONTH_INDEX, t.TARGET_AMOUNT, t.LAUNCH_PRICE,
      CASE sl.SLOT WHEN 'DIGITAL' THEN 3 WHEN 'PHYSICAL' THEN 4 ELSE IFF(sa.CATEGORY_ID IS NULL, 3, rc.CATEGORY_ID) END AS CAT_ID,
      CASE sl.SLOT WHEN 'DIGITAL' THEN cw.WEIGHT * IFF(hp.GAME_ID IS NULL, 1, t.DIGITAL_SHARE)
                   WHEN 'PHYSICAL' THEN cw.WEIGHT * (1 - t.DIGITAL_SHARE) ELSE cw.WEIGHT END AS W
    FROM t
    JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_WEIGHTS cw ON cw.PROFILE = t.PROFILE AND cw.LIFECYCLE_TAG = t.LIFECYCLE_TAG
    LEFT JOIN ONTOLOGY_DEMO.GAME_SALES.REVENUE_CATEGORIES rc ON rc.CATEGORY_NAME = cw.CATEGORY_NAME
    LEFT JOIN has_phys hp ON hp.GAME_ID = t.GAME_ID
    LEFT JOIN sku_av sa ON sa.GAME_ID = t.GAME_ID AND sa.REVENUE_MONTH = t.REVENUE_MONTH AND sa.CATEGORY_ID = rc.CATEGORY_ID
    JOIN (SELECT * FROM VALUES ('DIGITAL'), ('PHYSICAL'), ('ADDON') AS v(SLOT)) sl
      ON (cw.CATEGORY_NAME = 'BASE_GAME' AND sl.SLOT = 'DIGITAL')
      OR (cw.CATEGORY_NAME = 'BASE_GAME' AND sl.SLOT = 'PHYSICAL' AND hp.GAME_ID IS NOT NULL)
      OR (cw.CATEGORY_NAME <> 'BASE_GAME' AND sl.SLOT = 'ADDON')
  ), split AS (
    SELECT GAME_ID, REVENUE_MONTH, MONTH_INDEX, TARGET_AMOUNT, LAUNCH_PRICE, CAT_ID, SUM(W) AS W
    FROM split_raw GROUP BY 1, 2, 3, 4, 5, 6
  ), amt AS (
    SELECT s.*, ROUND(s.TARGET_AMOUNT * s.W, 2) AS A, ROW_NUMBER() OVER (PARTITION BY s.GAME_ID, s.REVENUE_MONTH ORDER BY s.W DESC, s.CAT_ID) AS WR
    FROM split s
  ), cat_month AS (
    SELECT a.GAME_ID, a.REVENUE_MONTH, a.MONTH_INDEX, a.CAT_ID,
      a.A + IFF(a.WR = 1, a.TARGET_AMOUNT - SUM(a.A) OVER (PARTITION BY a.GAME_ID, a.REVENUE_MONTH), 0) AS T,
      CASE WHEN a.CAT_ID IN (3, 4) THEN ROUND(a.LAUNCH_PRICE * CASE WHEN a.MONTH_INDEX < 12 THEN 1 WHEN a.MONTH_INDEX < 24 THEN 0.75 ELSE 0.5 END, 2)
           ELSE sa.AVG_PRICE END AS P
    FROM amt a LEFT JOIN sku_av sa ON sa.GAME_ID = a.GAME_ID AND sa.REVENUE_MONTH = a.REVENUE_MONTH AND sa.CATEGORY_ID = a.CAT_ID
  ),
  -- 3. Categories whose lifetime total is under half a unit fold into BASE_GAME_DIGITAL
  folded AS (
    SELECT c.GAME_ID, c.REVENUE_MONTH, c.MONTH_INDEX,
      IFF(c.CAT_ID <> 3 AND SUM(c.T) OVER (PARTITION BY c.GAME_ID, c.CAT_ID) < 0.5 * AVG(c.P) OVER (PARTITION BY c.GAME_ID, c.CAT_ID), 3, c.CAT_ID) AS CAT_ID,
      c.T
    FROM cat_month c
  ), cm AS (
    SELECT f.GAME_ID, f.REVENUE_MONTH, f.MONTH_INDEX, f.CAT_ID, SUM(f.T) AS T,
      MAX(CASE WHEN f.CAT_ID IN (3, 4) THEN ROUND(p.LAUNCH_PRICE * CASE WHEN f.MONTH_INDEX < 12 THEN 1 WHEN f.MONTH_INDEX < 24 THEN 0.75 ELSE 0.5 END, 2)
               ELSE sa.AVG_PRICE END) AS P
    FROM folded f
    JOIN ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_GAME_PROFILE p ON p.GAME_ID = f.GAME_ID
    LEFT JOIN sku_av sa ON sa.GAME_ID = f.GAME_ID AND sa.REVENUE_MONTH = f.REVENUE_MONTH AND sa.CATEGORY_ID = f.CAT_ID
    GROUP BY 1, 2, 3, 4
  ),
  -- 4. Carry-forward: a month that cannot sell one unit (ROUND(T/P) = 0) rolls into the next month that can;
  --    trailing ones roll back into the last such month; a category with no such month lands on its largest month.
  flg AS (
    SELECT cm.*, IFF(T > 0 AND ROUND(T / NULLIF(P, 0)) >= 1, 1, 0) AS OK,
      SUM(IFF(T > 0 AND ROUND(T / NULLIF(P, 0)) >= 1, 1, 0)) OVER (PARTITION BY GAME_ID, CAT_ID ORDER BY REVENUE_MONTH ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) AS G
    FROM cm
  ), dest AS (
    SELECT f.*,
      COALESCE(
        MAX(IFF(OK = 1, REVENUE_MONTH, NULL)) OVER (PARTITION BY GAME_ID, CAT_ID, IFF(G = 0, 1, G)),
        FIRST_VALUE(REVENUE_MONTH) OVER (PARTITION BY GAME_ID, CAT_ID ORDER BY T DESC, REVENUE_MONTH)) AS DEST_MONTH
    FROM flg f
  )
  SELECT d.GAME_ID, d.DEST_MONTH AS REVENUE_MONTH, d.CAT_ID AS CATEGORY_ID,
    SUM(d.T) AS TARGET_AMOUNT,
    MAX(IFF(d.REVENUE_MONTH = d.DEST_MONTH, d.P, NULL)) AS AVG_PRICE,
    GREATEST(1, ROUND(SUM(d.T) / NULLIF(MAX(IFF(d.REVENUE_MONTH = d.DEST_MONTH, d.P, NULL)), 0)))::NUMBER AS UNITS,
    COUNT(*) - 1 AS MONTHS_CARRIED_IN
  FROM dest d
  GROUP BY 1, 2, 3
  HAVING SUM(d.T) > 0;

  RETURN 'game_month_targets=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS)
    || ' total=' || (SELECT SUM(TARGET_AMOUNT) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GAME_REVENUE_TARGETS)
    || ' category_targets=' || (SELECT COUNT(*) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_TARGETS)
    || ' category_total=' || (SELECT SUM(TARGET_AMOUNT) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_TARGETS)
    || ' units=' || (SELECT SUM(UNITS) FROM ONTOLOGY_DEMO.GAME_SALES_GEN.GEN_CATEGORY_TARGETS);
END;
$$;
