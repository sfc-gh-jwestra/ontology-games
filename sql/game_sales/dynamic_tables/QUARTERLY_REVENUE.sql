create or replace dynamic table ONTOLOGY_DEMO.GAME_SALES.QUARTERLY_REVENUE(
	TITLE_ID,
	REVENUE_YEAR,
	REVENUE_QUARTER,
	QUARTERLY_INCOME,
	CUMULATIVE_INCOME
) target_lag = '1 hour' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as
SELECT TITLE_ID,
       YEAR(REVENUE_MONTH) AS REVENUE_YEAR,
       QUARTER(REVENUE_MONTH) AS REVENUE_QUARTER,
       SUM(MONTHLY_INCOME) AS QUARTERLY_INCOME,
       MAX(CUMULATIVE_INCOME) AS CUMULATIVE_INCOME
FROM ONTOLOGY_DEMO.GAME_SALES.MONTHLY_REVENUE
GROUP BY TITLE_ID, YEAR(REVENUE_MONTH), QUARTER(REVENUE_MONTH);
