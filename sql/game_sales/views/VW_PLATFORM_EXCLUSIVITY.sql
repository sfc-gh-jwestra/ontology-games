create or replace view ONTOLOGY_DEMO.GAME_SALES.VW_PLATFORM_EXCLUSIVITY(
	TITLE_ID,
	TITLE_NAME,
	INCOME,
	PLATFORM_ID,
	PLATFORM_NAME,
	IS_EXCLUSIVE,
	EXCLUSIVITY_TYPE,
	EXCLUSIVE_START,
	EXCLUSIVE_END,
	EXCLUSIVITY_NOTE,
	IS_CURRENTLY_EXCLUSIVE
) as
SELECT
    t.TITLE_ID, t.TITLE_NAME, gr.INCOME,
    p.PLATFORM_ID, p.PLATFORM_NAME,
    gp.IS_EXCLUSIVE,
    gp.EXCLUSIVITY_TYPE,
    gp.EXCLUSIVE_START,
    gp.EXCLUSIVE_END,
    gp.EXCLUSIVITY_NOTE,
    CASE
        WHEN gp.EXCLUSIVITY_TYPE = 'PERMANENT' THEN TRUE
        WHEN gp.EXCLUSIVITY_TYPE = 'TIMED' AND gp.EXCLUSIVE_END >= CURRENT_DATE() THEN TRUE
        ELSE FALSE
    END AS IS_CURRENTLY_EXCLUSIVE
FROM ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS gp
JOIN ONTOLOGY_DEMO.GAME_SALES.TITLES t ON gp.TITLE_ID = t.TITLE_ID
JOIN ONTOLOGY_DEMO.GAME_SALES.PLATFORMS p ON gp.PLATFORM_ID = p.PLATFORM_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_SALES.GAME_REVENUE gr ON t.TITLE_ID = gr.TITLE_ID
WHERE gp.IS_EXCLUSIVE = 'Y';
