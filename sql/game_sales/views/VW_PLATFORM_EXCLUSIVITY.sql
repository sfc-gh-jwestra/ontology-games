CREATE OR REPLACE VIEW ONTOLOGY_DEMO.GAME_SALES.VW_PLATFORM_EXCLUSIVITY (
	GAME_ID,
	GAME_NAME,
	INCOME,
	PLATFORM_ID,
	PLATFORM_NAME,
	IS_EXCLUSIVE,
	EXCLUSIVITY_TYPE,
	EXCLUSIVE_START,
	EXCLUSIVE_END,
	EXCLUSIVITY_NOTE,
	IS_CURRENTLY_EXCLUSIVE
) AS
SELECT
    g.GAME_ID, g.GAME_NAME, gr.INCOME,
    p.PLATFORM_ID, p.PLATFORM_NAME,
    gp.IS_EXCLUSIVE,
    gp.EXCLUSIVITY_TYPE,
    gp.EXCLUSIVE_START,
    gp.EXCLUSIVE_END,
    gp.EXCLUSIVITY_NOTE,
    CASE
        WHEN gp.EXCLUSIVITY_TYPE = 'PERMANENT' THEN TRUE
        WHEN gp.EXCLUSIVITY_TYPE = 'TIMED' AND gp.EXCLUSIVE_END >= CURRENT_DATE() THEN TRUE
        ELSE FALSE
    END AS IS_CURRENTLY_EXCLUSIVE
FROM ONTOLOGY_DEMO.GAME_SALES.GAME_PLATFORMS gp
JOIN ONTOLOGY_DEMO.GAME_SALES.GAMES g ON gp.GAME_ID = g.GAME_ID
JOIN ONTOLOGY_DEMO.GAME_SALES.PLATFORMS p ON gp.PLATFORM_ID = p.PLATFORM_ID
LEFT JOIN ONTOLOGY_DEMO.GAME_SALES.GAME_REVENUE gr ON g.GAME_ID = gr.GAME_ID
WHERE gp.IS_EXCLUSIVE = TRUE;
