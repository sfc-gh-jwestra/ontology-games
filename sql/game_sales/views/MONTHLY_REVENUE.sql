create or replace view ONTOLOGY_DEMO.GAME_SALES.MONTHLY_REVENUE(
	TITLE_ID,
	REVENUE_MONTH,
	MONTHLY_INCOME,
	CUMULATIVE_INCOME,
	REVENUE_SOURCE
) COMMENT='Per-title monthly revenue by monetization type, derived from DIGITAL_PRODUCT_TRANSACTIONS and title-specific SUBSCRIPTION_CHARGES. REVENUE_SOURCE is the REVENUE_TYPES.MONETIZATION_TYPE. CUMULATIVE_INCOME is the running total per title through the month.'
 as
WITH by_category AS (
    SELECT dp.TITLE_ID, DATE_TRUNC('MONTH', dpt.TRANSACTION_TIMESTAMP)::DATE AS REVENUE_MONTH,
           rt.MONETIZATION_TYPE AS REVENUE_SOURCE, SUM(dpt.GROSS_REVENUE) AS MONTHLY_INCOME
    FROM ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS dpt
    JOIN ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS dp ON dpt.DIGITAL_PRODUCT_ID = dp.DIGITAL_PRODUCT_ID
    JOIN ONTOLOGY_DEMO.GAME_SALES.REVENUE_TYPES rt ON dp.CATEGORY_ID = rt.CATEGORY_ID
    GROUP BY 1, 2, 3
    UNION ALL
    SELECT sp.GAME_ID, DATE_TRUNC('MONTH', sc.CHARGE_TIMESTAMP)::DATE, 'SUBSCRIPTION', SUM(sc.GROSS_REVENUE)
    FROM ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_CHARGES sc
    JOIN ONTOLOGY_DEMO.GAME_SALES.SUBSCRIPTION_PLANS sp ON sc.PLAN_ID = sp.PLAN_ID
    WHERE sp.GAME_ID IS NOT NULL
    GROUP BY 1, 2
), month_totals AS (
    SELECT TITLE_ID, REVENUE_MONTH, SUM(MONTHLY_INCOME) AS MONTH_TOTAL
    FROM by_category GROUP BY TITLE_ID, REVENUE_MONTH
), cumulative AS (
    SELECT TITLE_ID, REVENUE_MONTH,
           SUM(MONTH_TOTAL) OVER (PARTITION BY TITLE_ID ORDER BY REVENUE_MONTH) AS CUMULATIVE_INCOME
    FROM month_totals
)
SELECT b.TITLE_ID, b.REVENUE_MONTH, b.MONTHLY_INCOME, c.CUMULATIVE_INCOME, b.REVENUE_SOURCE
FROM by_category b JOIN cumulative c USING (TITLE_ID, REVENUE_MONTH);
