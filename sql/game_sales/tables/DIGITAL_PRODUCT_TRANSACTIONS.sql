create or replace TABLE ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCT_TRANSACTIONS (
	TRANSACTION_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	DIGITAL_PRODUCT_ID NUMBER(38,0) NOT NULL,
	GAME_ID NUMBER(38,0),
	ACCOUNT_ID NUMBER(38,0),
	TRANSACTION_TIMESTAMP TIMESTAMP_NTZ(9) NOT NULL,
	QUANTITY NUMBER(38,0) DEFAULT 1,
	UNIT_PRICE FLOAT,
	GROSS_REVENUE FLOAT,
	PLATFORM_COMMISSION_PCT FLOAT,
	NET_DEVELOPER_REVENUE FLOAT,
	PLATFORM_ID NUMBER(38,0) COMMENT 'Platform version / store the purchase was for (FK GAME_SALES.PLATFORMS). Drives store commission: PlayStation platforms 0%, other stores 30%.',
	primary key (TRANSACTION_ID),
	foreign key (DIGITAL_PRODUCT_ID) references ONTOLOGY_DEMO.GAME_SALES.DIGITAL_PRODUCTS(DIGITAL_PRODUCT_ID),
	foreign key (ACCOUNT_ID) references ONTOLOGY_DEMO.GAME_SALES.CUSTOMER_ACCOUNTS(ACCOUNT_ID),
	foreign key (GAME_ID) references ONTOLOGY_DEMO.GAME_SALES.GAMES(GAME_ID),
	foreign key (PLATFORM_ID) references ONTOLOGY_DEMO.GAME_SALES.PLATFORMS(PLATFORM_ID)
)COMMENT='Digital purchase transactions for every DIGITAL_PRODUCTS category. GAME_ID is denormalized from DIGITAL_PRODUCTS. GROSS_REVENUE minus NET_DEVELOPER_REVENUE is the platform commission.'
;
