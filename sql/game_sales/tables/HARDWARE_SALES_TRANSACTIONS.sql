create or replace TABLE ONTOLOGY_DEMO.GAME_SALES.HARDWARE_SALES_TRANSACTIONS (
	TRANSACTION_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	HARDWARE_PRODUCT_ID NUMBER(38,0) NOT NULL,
	BUYER_ID NUMBER(38,0),
	SALE_TIMESTAMP TIMESTAMP_NTZ(9) NOT NULL,
	REGION VARCHAR(16777216),
	QUANTITY NUMBER(38,0) DEFAULT 1,
	UNIT_PRICE FLOAT,
	GROSS_REVENUE FLOAT,
	primary key (TRANSACTION_ID),
	foreign key (HARDWARE_PRODUCT_ID) references ONTOLOGY_DEMO.GAME_SALES.HARDWARE_PRODUCTS(HARDWARE_PRODUCT_ID)
)COMMENT='Hardware sale transactions (consoles and peripherals). ACCOUNT_ID is null for anonymous retail purchases. Not attributable to a single game.'
