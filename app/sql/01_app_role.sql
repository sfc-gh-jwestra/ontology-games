-- Ontology vs Baseline compare app: the role Live mode runs as. Run as ACCOUNTADMIN, top to bottom.
-- There is no app login. Live mode opens a connections.toml profile (SNOWFLAKE_CONNECTION_NAME) and
-- switches to ONTOLOGY_APP_ROLE with no secondary roles, so this role needs direct grants.
-- Recorded mode, Setup and Analysis never connect to Snowflake.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ONTOLOGY_APP_ROLE;
-- Grant the app role to whoever runs this script (the installing user).
SET INSTALL_USER = CURRENT_USER();
GRANT ROLE ONTOLOGY_APP_ROLE TO USER IDENTIFIER($INSTALL_USER);
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE ONTOLOGY_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE ONTOLOGY_APP_ROLE;
-- Semantic views live with their data (install/03); the cross-domain view imports the other three.
GRANT SELECT, REFERENCES ON SEMANTIC VIEW ONTOLOGY_DEMO.GAME_CATALOG.SV_GAME_CATALOG TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT, REFERENCES ON SEMANTIC VIEW ONTOLOGY_DEMO.GAME_CATALOG.SV_GENRE_TAXONOMY TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT, REFERENCES ON SEMANTIC VIEW ONTOLOGY_DEMO.GAME_SALES.SV_GAME_COMMERCE TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT, REFERENCES ON SEMANTIC VIEW ONTOLOGY_DEMO.GAME_CATALOG.SV_GAMING_CROSS_DOMAIN TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON ALL AGENTS IN SCHEMA ONTOLOGY_DEMO.AGENTS TO ROLE ONTOLOGY_APP_ROLE;
-- Business Ontology (account-level, per domain). READ = approved nodes, relationships, representations.
-- Ontology search checks domain READ at query time; agent USAGE does not grant it.
-- Domain grants are not shown by SHOW GRANTS (preview); verify by querying as the role.
GRANT READ ON ONTOLOGY DOMAIN "Game Catalog" TO ROLE ONTOLOGY_APP_ROLE;
GRANT READ ON ONTOLOGY DOMAIN "Game Commerce" TO ROLE ONTOLOGY_APP_ROLE;
GRANT READ ON ONTOLOGY DOMAIN "Genre Taxonomy" TO ROLE ONTOLOGY_APP_ROLE;
-- Only if this role should also author/approve nodes (repeat per domain):
-- GRANT MODIFY ON ONTOLOGY DOMAIN "Game Catalog" TO ROLE ONTOLOGY_APP_ROLE;

-- Router demo CoWork profile (created in install/03). GAMING_PROFILE_USER inherits the data grants
-- above and adds USAGE on the profile at all three levels (database, schema, agent).
-- scripts/agent_routing_check.sql runs as this role. Granting it does not change your CoWork view:
-- CoWork uses your DEFAULT_ROLE (see documentation/how-to-demo-optional-cowork_profiles.md).
CREATE ROLE IF NOT EXISTS GAMING_PROFILE_USER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE GAMING_PROFILE_USER;
GRANT ROLE ONTOLOGY_APP_ROLE TO ROLE GAMING_PROFILE_USER;
GRANT USAGE ON DATABASE SNOWFLAKE_INTELLIGENCE TO ROLE GAMING_PROFILE_USER;
GRANT USAGE ON SCHEMA SNOWFLAKE_INTELLIGENCE.PROFILES TO ROLE GAMING_PROFILE_USER;
GRANT USAGE ON AGENT SNOWFLAKE_INTELLIGENCE.PROFILES.GAMING_PROFILE TO ROLE GAMING_PROFILE_USER;
GRANT ROLE GAMING_PROFILE_USER TO USER IDENTIFIER($INSTALL_USER);

-- Check: the role can see both agents and the semantic views.
SHOW GRANTS TO ROLE ONTOLOGY_APP_ROLE;
