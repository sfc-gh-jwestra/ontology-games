-- Ontology vs Baseline compare app: local OAuth setup. Run as ACCOUNTADMIN, top to bottom.
-- The app runs on localhost; users sign in with Snowflake OAuth and pick a role from APP_ROLES in .env.

USE ROLE ACCOUNTADMIN;

-- 1. OAuth client for the local app. The redirect goes through the Vite dev server (:5173),
--    which proxies /oauth to FastAPI, so cookies stay on one origin.
CREATE SECURITY INTEGRATION IF NOT EXISTS ONTOLOGY_COMPARE_LOCAL_OAUTH
  TYPE = OAUTH
  ENABLED = TRUE
  OAUTH_CLIENT = CUSTOM
  OAUTH_CLIENT_TYPE = 'CONFIDENTIAL'
  OAUTH_REDIRECT_URI = 'http://localhost:5173/oauth/callback'
  OAUTH_ALLOW_NON_TLS_REDIRECT_URI = TRUE
  OAUTH_ISSUE_REFRESH_TOKENS = TRUE
  OAUTH_REFRESH_TOKEN_VALIDITY = 86400
  OAUTH_USE_SECONDARY_ROLES = NONE   -- session uses only the role picked at sign-in
  COMMENT = 'Local dev login for app/ (ontology compare UI)';

-- The backend reads the client ID/secret itself on first sign-in (oauth.py). Run this only to inspect them.
-- SELECT SYSTEM$SHOW_OAUTH_CLIENT_SECRETS('ONTOLOGY_COMPARE_LOCAL_OAUTH');

-- 2. Direct grants for ONTOLOGY_APP_ROLE. The SPCS setup only gave it caller grants,
--    which do nothing outside a service; an OAuth session needs real privileges.
CREATE ROLE IF NOT EXISTS ONTOLOGY_APP_ROLE;
GRANT ROLE ONTOLOGY_APP_ROLE TO USER JWESTRA;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE ONTOLOGY_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ONTOLOGY_DEMO TO ROLE ONTOLOGY_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE ONTOLOGY_APP_ROLE;
GRANT SELECT ON SEMANTIC VIEW ONTOLOGY_DEMO.ONTOLOGY_AGENTS.GAMING_BASELINE_SV TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON AGENT ONTOLOGY_DEMO.ONTOLOGY_AGENTS.GAMING_BASELINE_AGENT TO ROLE ONTOLOGY_APP_ROLE;
GRANT USAGE ON AGENT ONTOLOGY_DEMO.ONTOLOGY_AGENTS.GAMING_BON_AGENT TO ROLE ONTOLOGY_APP_ROLE;
-- Business Ontology (account-level, per domain). READ = approved nodes, relationships, representations.
-- Ontology search checks domain READ at query time; agent USAGE does not grant it.
-- Domain grants are not shown by SHOW GRANTS (preview); verify by querying as the role.
GRANT READ ON ONTOLOGY DOMAIN "Game Catalog" TO ROLE ONTOLOGY_APP_ROLE;
GRANT READ ON ONTOLOGY DOMAIN "Game Commerce" TO ROLE ONTOLOGY_APP_ROLE;
GRANT READ ON ONTOLOGY DOMAIN "Genre Taxonomy" TO ROLE ONTOLOGY_APP_ROLE;
