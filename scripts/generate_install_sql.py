"""
Generate the install/NN-*.sql files that embed project sources.

The sources stay the single source of truth; re-run this after editing any of them:

  install/02-load-data.sql               data/<SCHEMA>/*.parquet + sql/<SCHEMA>/**.sql
  install/03-deploy-sv-and-agents.sql    semantic_views/*.yaml + agents/*.yaml + agents/router/*.yaml
  install/04a-build-ontology.sql         scripts/build_ontology.py (first install)
  install/04b-refresh-ontology.sql       scripts/build_ontology.py (re-install)

install/01-setup-db.sql is written by hand. Every file is run from the repo root
(PUT paths are relative) with: snow sql -c <connection> --enable-templating NONE -f <file>

Usage: python3 scripts/generate_install_sql.py
"""
import importlib.util
import json
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
INSTALL = ROOT / "install"
DB = "ONTOLOGY_DEMO"
SCHEMAS = ["GAME_CATALOG", "GAME_SALES"]
AGENT_SCHEMA = f"{DB}.AGENTS"
# Semantic views in create order: each one comes after the views it imports. Each YAML's first
# line names its target, e.g. "# Semantic view ONTOLOGY_DEMO.GAME_CATALOG.SV_GAME_CATALOG".
SV_ORDER = ["SV_GAME_CATALOG", "SV_GENRE_TAXONOMY", "SV_GAME_COMMERCE", "SV_GAMING_CROSS_DOMAIN"]
DATA_STAGE = f"{DB}.PUBLIC.DATA_STAGE"
FILE_FORMAT = f"{DB}.PUBLIC.PARQUET_FF"
# Object DDL types created after the base tables, in dependency order (see sorted_objects).
OBJECT_DIRS = ["functions", "procedures", "views", "dynamic_tables"]
# Agent object metadata that is not part of the agent specification YAML.
# Create order: the router comes last because it delegates to the others.
AGENT_META = {
    "GAMING_BASELINE_AGENT": ("agents", "Baseline: text-to-SQL over SV_GAMING_CROSS_DOMAIN only (no Business Ontology)",
                              "Gaming Baseline Assistant"),
    "GAMING_BON_AGENT": ("agents", "BON agent: native Business Ontology search + text-to-SQL over SV_GAMING_CROSS_DOMAIN",
                         "Gaming BON Assistant"),
    "GAMING_CATALOG_AGENT": ("agents/router", "Router demo: Game Catalog domain agent over SV_GAME_CATALOG",
                             "Gaming Catalog Agent"),
    "GAMING_GENRE_AGENT": ("agents/router", "Router demo: Genre Taxonomy domain agent over SV_GENRE_TAXONOMY",
                           "Gaming Genre Agent"),
    "GAMING_SALES_AGENT": ("agents/router", "Router demo: Game Commerce domain agent over SV_GAME_COMMERCE",
                           "Gaming Sales Agent"),
    "GAMING_ROUTER_AGENT": ("agents/router", "Router demo: delegates to the catalog, genre, sales and baseline agents (agent_router)",
                            "Gaming Router Agent"),
}


def load_module(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def header(step, sources):
    return (f"-- {step}\n"
            f"-- GENERATED by scripts/generate_install_sql.py from {sources}. Do not edit by hand.\n"
            f"-- Run from the repo root: snow sql -c <connection> --enable-templating NONE -f install/{step}.sql\n\n")


def dollar(text, what):
    if "$$" in text:
        raise ValueError(f"{what} contains '$$', which breaks dollar-quoting")
    return f"$${text}$$"


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def ddl(path):
    text = path.read_text().strip()
    return text if text.endswith(";") else text + ";"


def sorted_objects():
    """Functions, procedures, views and dynamic tables, ordered so each comes after what it references."""
    objs = {}
    for s in SCHEMAS:
        for d in OBJECT_DIRS:
            for f in sorted((ROOT / "sql" / s / d).glob("*.sql")):
                objs[f.stem.upper()] = f
    deps = {name: {o for o in objs if o != name and re.search(rf"\b{o}\b", f.read_text(), re.I)}
            for name, f in objs.items()}
    out, done = [], set()

    def visit(name, path=()):
        if name in done:
            return
        if name in path:
            raise ValueError(f"Dependency cycle: {' -> '.join(path + (name,))}")
        for d in sorted(deps[name]):
            visit(d, path + (name,))
        done.add(name)
        out.append(objs[name])

    for name in objs:
        visit(name)
    return out


def gen_02():
    parts = [header("02-load-data", "data/ and sql/"),
             "-- Order: (a) upload parquet, (b) base tables, (c) COPY INTO, (d) functions, procedures,\n"
             "-- views and dynamic tables in dependency order. Table DDL is CREATE OR REPLACE.\n\n",
             "-- (a) Upload parquet files\n"]
    for s in SCHEMAS:
        parts.append(f"PUT 'file://data/{s}/*.parquet' @{DATA_STAGE}/{s}/ AUTO_COMPRESS = FALSE OVERWRITE = TRUE PARALLEL = 8;\n")
    parts.append("\n-- (b) Base tables\n")
    tables = [(s, f) for s in SCHEMAS for f in sorted((ROOT / "sql" / s / "tables").glob("*.sql"))
              if not f.stem.startswith("BACKUP_")]  # point-in-time backups, not part of the demo
    # A foreign key must reference a table that already exists, so referenced tables go first.
    names = {f"{s}.{f.stem}" for s, f in tables}
    fk_deps = {f"{s}.{f.stem}": set(re.findall(rf"references\s+{DB}\.(\w+\.\w+)", ddl(f), re.I))
               & names for s, f in tables}
    ordered = []

    def visit(n):
        if n not in ordered:
            for d in sorted(fk_deps[n] - {n}):
                visit(d)
            ordered.append(n)
    for s, f in tables:
        visit(f"{s}.{f.stem}")
    tables.sort(key=lambda sf: ordered.index(f"{sf[0]}.{sf[1].stem}"))
    for s, f in tables:
        parts.append(f"-- {s}.{f.stem}\n{ddl(f)}\n\n")
    parts.append("-- (c) Load each table that has a data file\n")
    for s, f in tables:
        t = f.stem
        if not list((ROOT / "data" / s).glob(f"{t}_[0-9]*.parquet")):
            parts.append(f"-- {s}.{t}: no data file, left empty\n")
            continue
        # PATTERN anchors on "/<TABLE>_<n>_" so PLATFORMS does not match GAME_PLATFORMS files.
        parts.append(
            f"COPY INTO {DB}.{s}.{t} FROM @{DATA_STAGE}/{s}/\n"
            f"  PATTERN = '(.*/)?{t}_[0-9]+_[0-9]+_[0-9]+[.]snappy[.]parquet'\n"
            f"  FILE_FORMAT = (FORMAT_NAME = '{FILE_FORMAT}')\n"
            f"  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = ABORT_STATEMENT;\n")
    parts.append("\n-- (d) Functions, procedures, views and dynamic tables\n")
    for f in sorted_objects():
        parts.append(f"-- {f.relative_to(ROOT / 'sql')}\n{ddl(f)}\n\n")
    return "".join(parts)


def semantic_views():
    """(schema FQN, name, path, text) for each semantic view, in SV_ORDER."""
    found = {f.stem: f for f in (ROOT / "semantic_views").glob("*.yaml")}
    if set(found) != set(SV_ORDER):
        raise ValueError(f"semantic_views/ has {sorted(found)}, SV_ORDER has {SV_ORDER}")
    out = []
    for stem in SV_ORDER:
        f = found[stem]
        text = f.read_text()
        m = re.match(rf"# Semantic view ({DB}\.\w+)\.(\w+)\n", text)
        if not m or m.group(2) != yaml.safe_load(text)["name"]:
            raise ValueError(f"{f.name}: first line must be '# Semantic view {DB}.<SCHEMA>.<name in YAML>'")
        out.append((m.group(1), m.group(2), f, text))
    return out


def gen_03():
    parts = [header("03-deploy-sv-and-agents", "semantic_views/*.yaml, agents/*.yaml and agents/router/*.yaml"),
             "-- Each semantic view lives in the schema of its data; SV_GAMING_CROSS_DOMAIN (imports the other three)\n"
             f"-- lives in GAME_CATALOG. All agents live in {AGENT_SCHEMA}. Grants for the app role: app/sql/01_local_oauth.sql.\n\n",
             f"CREATE SCHEMA IF NOT EXISTS {AGENT_SCHEMA};\n\n"]
    svs = semantic_views()
    parts.append("-- Drop importing views before the views they import\n")
    parts += [f"DROP SEMANTIC VIEW IF EXISTS {schema}.{name};\n" for schema, name, _, _ in reversed(svs)]
    parts.append("\n")
    for schema, name, f, text in svs:
        parts.append(f"-- {f.name} -> {schema}.{name}\n"
                     f"CALL SYSTEM$CREATE_SEMANTIC_VIEW_FROM_YAML('{schema}', {dollar(chr(10) + text + chr(10), f.name)});\n\n")
    found = {f.stem for d in ("agents", "agents/router") for f in (ROOT / d).glob("*.yaml")}
    if found != set(AGENT_META):
        raise ValueError(f"agent YAMLs {sorted(found)} do not match AGENT_META {sorted(AGENT_META)}")
    for name, (folder, comment, display) in AGENT_META.items():
        f = ROOT / folder / f"{name}.yaml"
        profile = json.dumps({"display_name": display})
        parts.append(f"-- {folder}/{f.name}\nCREATE OR REPLACE AGENT {AGENT_SCHEMA}.{name}\n"
                     f"  COMMENT = {sql_str(comment)}\n"
                     f"  PROFILE = {sql_str(profile)}\n"
                     f"  FROM SPECIFICATION {dollar(chr(10) + f.read_text() + chr(10), f.name)};\n\n")
    return "".join(parts)


def gen_04a():
    bon = load_module("build_ontology")
    return (header("04a-build-ontology", "scripts/build_ontology.py")
            + "-- First install only: the domain calls fail if the domains already exist.\n"
              "-- install.sh runs this when SYSTEM$GET_GLOSSARY_SUMMARY() shows no domains, otherwise 04b.\n\n"
            + bon.build_sql())


def gen_04b():
    bon = load_module("build_ontology")
    return (header("04b-refresh-ontology", "scripts/build_ontology.py")
            + "-- Re-install: rewrite every term's description and formula in place. Term IDs, relationships\n"
              "-- and representations are kept. New terms or edges need 04a on a clean account.\n\n"
            + bon.refresh_sql())


GENERATED = {
    "02-load-data.sql": gen_02,
    "03-deploy-sv-and-agents.sql": gen_03,
    "04a-build-ontology.sql": gen_04a,
    "04b-refresh-ontology.sql": gen_04b,
}


def main():
    INSTALL.mkdir(exist_ok=True)
    for name, fn in GENERATED.items():
        text = fn()
        (INSTALL / name).write_text(text)
        print(f"Wrote install/{name} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
